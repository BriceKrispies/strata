//! The backend's internal HTTP API.
//!
//! Every request carries the service token in [`HEADER_SERVICE`]. The BFF states which site it
//! is serving in [`HEADER_SITE`] (from its own configuration, never from the browser), passes
//! the browser's opaque session token in [`HEADER_SESSION`] when there is one, and a
//! correlation id in [`HEADER_CORRELATION`]. The backend derives tenant and principal from the
//! session it holds; a session of another tenant than the site is treated as no session.

use serde::{Deserialize, Serialize};
use serde_json::Value as Json;
use std::collections::BTreeMap;
use strata_kernel::Check;

pub const HEADER_SERVICE: &str = "x-strata-service";
pub const HEADER_SITE: &str = "x-strata-site";
pub const HEADER_SESSION: &str = "x-strata-session";
pub const HEADER_CORRELATION: &str = "x-correlation-id";

/// A correlation id is generated by whoever starts an operation and must look like this to be
/// passed on: 1 to 64 characters of `[A-Za-z0-9_.:-]`.
pub fn valid_correlation(id: &str) -> bool {
    !id.is_empty()
        && id.len() <= 64
        && id
            .chars()
            .all(|c| c.is_ascii_alphanumeric() || matches!(c, '_' | '.' | ':' | '-'))
}

/// The machine-readable class of a failure. Maps one-to-one onto an HTTP status.
#[derive(Clone, Copy, Debug, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum ErrorCode {
    Unauthenticated,
    Forbidden,
    NotFound,
    Conflict,
    Invalid,
    Throttled,
    Unavailable,
    Internal,
}

impl ErrorCode {
    pub fn status(self) -> u16 {
        match self {
            ErrorCode::Unauthenticated => 401,
            ErrorCode::Forbidden => 403,
            ErrorCode::NotFound => 404,
            ErrorCode::Conflict => 409,
            ErrorCode::Invalid => 422,
            ErrorCode::Throttled => 429,
            ErrorCode::Unavailable => 503,
            ErrorCode::Internal => 500,
        }
    }
}

/// The body of every non-success reply, from the backend and from the BFF.
#[derive(Clone, Debug, PartialEq, Eq, Serialize, Deserialize)]
pub struct ErrorReply {
    pub code: ErrorCode,
    pub message: String,
    /// The kernel's rejection kind, when the kernel rejected the request.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub kind: Option<String>,
    /// The checks that failed, so a form can say which field is wrong.
    #[serde(default, skip_serializing_if = "Vec::is_empty")]
    pub failed: Vec<Check>,
    pub correlation: String,
}

#[derive(Clone, Debug, Serialize, Deserialize)]
pub struct LoginRequest {
    pub login: String,
    pub password: String,
}

/// What the BFF and the browser may know about the current session. Never the token.
#[derive(Clone, Debug, PartialEq, Eq, Serialize, Deserialize)]
pub struct SessionView {
    pub authenticated: bool,
    pub tenant: String,
    pub tenant_name: String,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub session_id: Option<String>,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub principal: Option<String>,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub display_name: Option<String>,
    pub roles: Vec<String>,
    /// Sent back by the browser in `x-csrf-token` on every state-changing request.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub csrf_token: Option<String>,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub expires_at: Option<i64>,
    /// Actions some policy could grant this principal, by object type. For deciding what to
    /// offer; the kernel decides each request for real.
    pub may: BTreeMap<String, Vec<String>>,
    pub may_manage_schema: bool,
}

/// The current session as the backend sees it, and why there is none if a token did not hold.
#[derive(Clone, Debug, Serialize, Deserialize)]
pub struct SessionReply {
    pub session: SessionView,
    pub state: crate::ws::SessionState,
}

#[derive(Clone, Debug, Serialize, Deserialize)]
pub struct LoginReply {
    /// The opaque session token. The BFF puts it in an HttpOnly cookie and nowhere else.
    pub token: String,
    pub session: SessionView,
}

#[derive(Clone, Debug, Serialize, Deserialize)]
pub struct ViewRequest {
    pub path: String,
    #[serde(default)]
    pub request: BTreeMap<String, String>,
}

/// A record mutation with plain JSON field values; the backend coerces them by field type.
#[derive(Clone, Debug, Serialize, Deserialize)]
#[serde(tag = "op", rename_all = "snake_case")]
pub enum Mutation {
    Create {
        object: String,
        fields: serde_json::Map<String, Json>,
    },
    Update {
        object: String,
        id: u64,
        fields: serde_json::Map<String, Json>,
        #[serde(default)]
        expected_version: Option<u64>,
    },
    Delete {
        object: String,
        id: u64,
        #[serde(default)]
        expected_version: Option<u64>,
    },
}

#[derive(Clone, Debug, PartialEq, Eq, Serialize, Deserialize)]
pub struct MutationReply {
    pub object: String,
    pub id: u64,
    /// The record's new version; absent after a delete.
    pub version: Option<u64>,
    pub revision: u64,
    /// The tenant event sequence after this change. A client that has seen this sequence on its
    /// subscription has seen the effect of its own request.
    pub event_seq: u64,
    pub checks_passed: usize,
}

#[derive(Clone, Debug, Serialize, Deserialize)]
pub struct IdRequest {
    pub id: String,
}

#[derive(Clone, Debug, Serialize, Deserialize)]
pub struct Empty {}
