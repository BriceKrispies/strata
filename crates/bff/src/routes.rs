/// The WebSocket upgrade of the signed-in page: it must come from an allowed origin and carry the
/// session's request token, and the connection delivers only what its principal may read.
///
/// Implements: CT-098
async fn socket(
    State(bff): State<Shared>,
    headers: HeaderMap,
    Query(query): Query<BTreeMap<String, String>>,
    stop: Option<Extension<Shutdown>>,
    upgrade: WebSocketUpgrade,
) -> Result<Response, Failure> {
    let visit = visit(&bff, &headers)?;
    if !origin_allowed(&bff, &visit.site, &headers) {
        LOG.warn(
            "ws.origin_refused",
            &visit.correlation,
            json!({ "origin": text(&headers, ORIGIN) }),
        );
        return Err(Failure::new(
            ErrorCode::Forbidden,
            "This connection did not come from the site.",
            &visit.correlation,
        ));
    }
    // A browser cannot set a header on a socket, so the request token travels in the address.
    // The log lines of this process leave the query string out.
    let given = query.get("csrf").map_or("", String::as_str);
    if presented_token(&bff, &visit, given).await?.is_none() {
        LOG.warn("ws.token_refused", &visit.correlation, json!({}));
        return Err(Failure::new(
            ErrorCode::Forbidden,
            "This connection did not carry the request token of its session.",
            &visit.correlation,
        ));
    }
    // At most so many sockets per session and per source address; the places are held until the
    // socket closes.
    let places = bff
        .admission
        .socket(visit.token.as_deref(), visit.source.as_deref())
        .map_err(|message| {
            LOG.warn(
                "ws.cap_refused",
                &visit.correlation,
                json!({ "source": visit.source, "signed_in": visit.token.is_some() }),
            );
            Failure::new(ErrorCode::Throttled, message, &visit.correlation)
        })?;
    // The socket is registered with the server's drain, so that the server waits for it to send
    // its Close frame when the process is stopped. A server that has finished draining takes no
    // new sockets.
    let stop = stop.map(|Extension(stop)| stop);
    let held = match &stop {
        Some(stop) => Some(stop.hold().ok_or_else(|| {
            Failure::new(
                ErrorCode::Unavailable,
                "The service is stopping.",
                &visit.correlation,
            )
        })?),
        None => None,
    };
    Ok(upgrade
        .max_message_size(strata_protocol::ws::MAX_FRAME)
        .on_upgrade(move |browser| async move {
            relay::relay(bff, visit, places, browser, stop).await;
            drop(held);
        }))
}

/// Decode a query-string value: `+` is a space, `%XX` is a byte.
fn percent_decode(value: &str) -> String {
    let bytes = value.as_bytes();
    let mut out = Vec::with_capacity(bytes.len());
    let mut i = 0;
    while i < bytes.len() {
        let hex = |b: u8| (b as char).to_digit(16);
        match bytes[i] {
            b'+' => out.push(b' '),
            b'%' => {
                match (
                    bytes.get(i + 1).copied().and_then(hex),
                    bytes.get(i + 2).copied().and_then(hex),
                ) {
                    (Some(high), Some(low)) => {
                        out.push((high * 16 + low) as u8);
                        i += 2;
                    }
                    _ => out.push(b'%'),
                }
            }
            other => out.push(other),
        }
        i += 1;
    }
    String::from_utf8_lossy(&out).into_owned()
}

fn escape_html(text: &str) -> String {
    text.replace('&', "&amp;")
        .replace('<', "&lt;")
        .replace('>', "&gt;")
        .replace('"', "&quot;")
}

/// The page shell with the first view model and session embedded, so the first paint needs no
/// request. The data block is JSON, not script: `<` is escaped and the CSP allows no inline code.
///
/// Implements: CT-136, CT-137
async fn page(State(bff): State<Shared>, headers: HeaderMap, request: Request) -> Response {
    let visit = match visit(&bff, &headers) {
        Ok(visit) => visit,
        Err(failure) => return failure.into_response(),
    };
    let Some(index) = &bff.index else {
        let body = "The frontend has not been built. Run `npm run build` in web/, or use the development server.";
        return (StatusCode::SERVICE_UNAVAILABLE, body).into_response();
    };
    let path = request.uri().path().to_string();
    let query: BTreeMap<String, String> = request
        .uri()
        .query()
        .map(|q| {
            q.split('&')
                .filter_map(|pair| pair.split_once('='))
                .filter(|(name, value)| name.len() <= 32 && value.len() <= 200)
                .map(|(name, value)| (name.to_string(), percent_decode(value)))
                .collect()
        })
        .unwrap_or_default();
    let session = backend::<SessionReply>(&bff, &visit, "/internal/session", &json!({})).await;
    let view = view_model(&bff, &visit, &path, query, Paging::default()).await;
    let status = match &view {
        Err(Failure(reply)) if reply.code == ErrorCode::NotFound => StatusCode::NOT_FOUND,
        Err(Failure(reply)) if reply.code == ErrorCode::Unavailable => {
            StatusCode::SERVICE_UNAVAILABLE
        }
        _ => StatusCode::OK,
    };
    let view = view.ok();
    let site_name = session
        .as_ref()
        .map(|s| s.session.tenant_name.clone())
        .unwrap_or_else(|_| "Strata".into());
    // The same title the browser will set once it has drawn the page: the thing shown, then
    // the publication.
    let named = view.as_ref().and_then(|v| {
        // The title the view's screen states; a view no screen states one for keeps the title
        // its tenant schema gives it.
        match v["view"]
            .as_str()
            .and_then(screens::view_info)
            .and_then(|info| info.title)
        {
            Some(parts) => Some(title_text(v, parts)).filter(|text| !text.is_empty()),
            None => v["title"]
                .as_str()
                .filter(|text| !text.is_empty())
                .map(str::to_string),
        }
    });
    let title = named.map_or(site_name.clone(), |t| format!("{t} — {site_name}"));
    let description = view
        .as_ref()
        .and_then(|v| v["data"]["site"]["fields"]["tagline"].as_str())
        .unwrap_or("")
        .to_string();
    let theme = view
        .as_ref()
        .map(|v| v["theme"].clone())
        .unwrap_or_else(|| json!(theme::Theme::default()));
    let bootstrap = json!({
        "path": path,
        "session": session.ok().map(|reply| json!({ "session": with_request_token(&bff, &visit, reply.session), "state": reply.state })),
        "view": view,
    })
    .to_string()
    .replace('<', "\\u003c");
    let html = index
        .replace(
            "<html lang=\"en\">",
            &format!(
                "<html lang=\"en\" data-accent=\"{}\" data-paper=\"{}\">",
                theme["accent"].as_str().unwrap_or("moss"),
                theme["paper"].as_str().unwrap_or("linen")
            ),
        )
        .replace(
            "<title>Strata</title>",
            &format!("<title>{}</title>", escape_html(&title)),
        )
        .replace(
            "<!--strata:head-->",
            &format!(
                "<meta name=\"description\" content=\"{}\">",
                escape_html(&description)
            ),
        )
        .replace(
            "<!--strata:bootstrap-->",
            &format!(
                "<script type=\"application/json\" id=\"strata-bootstrap\">{bootstrap}</script>"
            ),
        );
    let mut response = (status, html).into_response();
    response.headers_mut().insert(
        CONTENT_TYPE,
        HeaderValue::from_static("text/html; charset=utf-8"),
    );
    response
        .headers_mut()
        .insert(CACHE_CONTROL, HeaderValue::from_static("no-store"));
    response
}

/// The address a request is attributed to: its TCP peer, or the client a trusted proxy reports.
fn source_of(bff: &Bff, request: &Request) -> Option<String> {
    let peer = request
        .extensions()
        .get::<ConnectInfo<SocketAddr>>()?
        .0
        .ip();
    let forwarded = request
        .headers()
        .get_all("x-forwarded-for")
        .iter()
        .filter_map(|value| value.to_str().ok())
        .collect::<Vec<_>>()
        .join(",");
    let forwarded = (!forwarded.is_empty()).then_some(forwarded);
    Some(client_address(peer, forwarded.as_deref(), &bff.cfg.trusted_proxies).to_string())
}

/// Whether a request is a page or a view read, the two that cost the backend calls and that the
/// per-source request rate applies to.
fn is_page_or_view(method: &Method, path: &str) -> bool {
    if path == "/api/view" {
        return true;
    }
    const OTHER: [&str; 9] = [
        "/api/",
        "/assets/",
        "/media/",
        "/ws",
        "/federation/",
        "/scim/",
        "/keys",
        "/.well-known/",
        "/token",
    ];
    *method == Method::GET && !OTHER.iter().any(|prefix| path.starts_with(prefix))
}

/// Forwarded headers arrive but no proxy is trusted: every visitor behind that proxy shares one
/// source. Said once per process.
fn warn_forwarded_without_proxies() {
    static SAID: std::sync::atomic::AtomicBool = std::sync::atomic::AtomicBool::new(false);
    if !SAID.swap(true, Ordering::Relaxed) {
        LOG.warn(
            "bff.forwarded_without_trusted_proxies",
            "",
            json!({ "hint": "set STRATA_TRUSTED_PROXIES to the addresses of the proxies in front of this process; until then every visitor behind them is one source" }),
        );
    }
}

/// Outside development, a request that carries `X-Forwarded-For` while no trusted proxy is
/// configured is refused: the header cannot be believed, so every visitor behind the proxy would
/// be one source, and a visitor that sends it itself would be hiding behind it. The reason is
/// named so that the operator finds the setting.
fn refuse_forwarded_without_proxies() -> Response {
    LOG.error(
        "bff.forwarded_refused",
        "",
        json!({ "reason": FORWARDED_REFUSAL, "hint": "set STRATA_TRUSTED_PROXIES to the addresses of the proxies in front of this process" }),
    );
    (StatusCode::BAD_REQUEST, FORWARDED_REFUSAL).into_response()
}

/// The reason a request with forwarded headers and no trusted proxies is refused.
pub const FORWARDED_REFUSAL: &str =
    "forwarded_without_trusted_proxies: this request carries X-Forwarded-For but STRATA_TRUSTED_PROXIES names no proxy";

/// Security headers on everything, and one log line per request. Also the one place that sets the
/// request's source: whatever a browser sent under that name is dropped first.
async fn envelope(State(bff): State<Shared>, mut request: Request, next: Next) -> Response {
    let started = Instant::now();
    request.headers_mut().remove(HEADER_SOURCE);
    if let Some(source) = source_of(&bff, &request) {
        if let Ok(value) = HeaderValue::from_str(&source) {
            request.headers_mut().insert(HEADER_SOURCE, value);
        }
    }
    let method = request.method().clone();
    let path = request.uri().path().to_string();
    if request.headers().contains_key("x-forwarded-for") && bff.cfg.trusted_proxies.is_empty() {
        if !bff.cfg.dev {
            return refuse_forwarded_without_proxies();
        }
        warn_forwarded_without_proxies();
    }
    // A host nobody knows may be a tenant created since the list was fetched; a list that has
    // aged out is fetched again. Both are rate limited (see `hosts`).
    let known = bff.site_of(host_name(request.headers())).is_some();
    crate::hosts::refresh_if_due(&bff, !known).await;
    if is_page_or_view(&method, &path) {
        if let Some(source) = text(request.headers(), HEADER_SOURCE) {
            if !bff
                .admission
                .request(source, strata_protocol::log::now_ms())
            {
                let mut response = (
                    StatusCode::TOO_MANY_REQUESTS,
                    "Too many requests from this address. Try again shortly.",
                )
                    .into_response();
                response
                    .headers_mut()
                    .insert("retry-after", HeaderValue::from_static("60"));
                return response;
            }
        }
    }
    let correlation = text(request.headers(), HEADER_CORRELATION)
        .filter(|id| valid_correlation(id))
        .unwrap_or("")
        .to_string();
    bff.in_flight.fetch_add(1, Ordering::Relaxed);
    // Source maps are built for development; they are not served.
    let mut response = if path.starts_with("/assets/") && path.ends_with(".map") {
        StatusCode::NOT_FOUND.into_response()
    } else {
        next.run(request).await
    };
    bff.in_flight.fetch_sub(1, Ordering::Relaxed);
    let response_status = response.status();
    let https = bff.origins().iter().any(|o| o.starts_with("https://"));
    let headers = response.headers_mut();
    // `trusted-types strata-worker` names the one policy the page creates (web/src/trusted-urls.js, the
    // kernel worker's address); `require-trusted-types-for 'script'` makes every script sink demand a typed value (GWY-253).
    // The development server serves its own page and sends none of these headers.
    let mut policy = "default-src 'self'; script-src 'self'; style-src 'self'; img-src 'self' data:; font-src 'self'; connect-src 'self'; worker-src 'self'; object-src 'none'; base-uri 'none'; form-action 'self'; frame-ancestors 'none'; require-trusted-types-for 'script'; trusted-types strata-worker".to_string();
    if https {
        // Only where the origin is https: on plain http the directive would break every
        // subresource of a development page.
        policy.push_str("; upgrade-insecure-requests");
        headers.insert(
            "strict-transport-security",
            HeaderValue::from_static("max-age=31536000; includeSubDomains"),
        );
    }
    if let Ok(policy) = HeaderValue::from_str(&policy) {
        headers.insert(CONTENT_SECURITY_POLICY, policy);
    }
    headers.insert(
        "permissions-policy",
        HeaderValue::from_static("camera=(), microphone=(), geolocation=(), payment=(), usb=()"),
    );
    headers.insert(
        "x-content-type-options",
        HeaderValue::from_static("nosniff"),
    );
    headers.insert("referrer-policy", HeaderValue::from_static("same-origin"));
    headers.insert("x-frame-options", HeaderValue::from_static("DENY"));
    if path.starts_with("/api/") {
        headers.insert(CACHE_CONTROL, HeaderValue::from_static("no-store"));
    } else if path.starts_with("/assets/")
        && (response_status.is_success() || response_status == StatusCode::NOT_MODIFIED)
    {
        headers.insert(
            CACHE_CONTROL,
            HeaderValue::from_static("public, max-age=31536000, immutable"),
        );
    }
    if path.starts_with("/api/") || method != Method::GET {
        // The query string is left out: a search term is the reader's business.
        LOG.info(
            "bff.request",
            &correlation,
            json!({ "method": method.as_str(), "path": path, "status": response.status().as_u16(), "ms": started.elapsed().as_millis() as u64 }),
        );
    }
    response
}

async fn api_not_found(headers: HeaderMap) -> Failure {
    let correlation = text(&headers, HEADER_CORRELATION).unwrap_or("").to_string();
    Failure::new(ErrorCode::NotFound, "No such endpoint.", &correlation)
}

/// A JSON answer that no cache keeps.
fn uncached(body: Json_) -> Response {
    let mut response = Json(body).into_response();
    response
        .headers_mut()
        .insert(CACHE_CONTROL, HeaderValue::from_static("no-store"));
    response
}

/// The body of a token request: JSON, or the form that OAuth clients send.
fn oauth_body(headers: &HeaderMap, body: &[u8]) -> Json_ {
    let json = text(headers, CONTENT_TYPE).is_some_and(|kind| kind.contains("json"));
    if json {
        return serde_json::from_slice(body).unwrap_or(Json_::Null);
    }
    Json_::Object(
        form_fields(body)
            .into_iter()
            .map(|(name, value)| (name, Json_::String(value)))
            .collect(),
    )
}

/// The token endpoint. A service account presents its credentials in the body, so nothing here
/// rests on a cookie: the request is made as no one's session.
///
/// Implements: TOK-001
async fn oauth_token(
    State(bff): State<Shared>,
    headers: HeaderMap,
    body: axum::body::Bytes,
) -> Result<Response, Failure> {
    let mut visit = visit(&bff, &headers)?;
    visit.token = None;
    let reply: Json_ = backend(
        &bff,
        &visit,
        "/internal/token",
        &oauth_body(&headers, &body),
    )
    .await?;
    Ok(uncached(reply))
}

