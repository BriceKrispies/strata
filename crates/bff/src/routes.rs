/// A failure reply with its status.
pub struct Failure(pub ErrorReply);

impl Failure {
    pub fn new(code: ErrorCode, message: &str, correlation: &str) -> Self {
        Failure(ErrorReply {
            code,
            message: message.to_string(),
            kind: None,
            failed: Vec::new(),
            correlation: correlation.to_string(),
        })
    }
}

impl IntoResponse for Failure {
    fn into_response(self) -> Response {
        let status =
            StatusCode::from_u16(self.0.code.status()).unwrap_or(StatusCode::INTERNAL_SERVER_ERROR);
        (status, Json(json!(self.0))).into_response()
    }
}

/// What this process established about a browser request before doing anything with it.
#[derive(Clone)]
pub struct Visit {
    pub site: TenantId,
    pub token: Option<String>,
    pub correlation: String,
    /// The visitor's address, as `envelope` established it from the connection and the trusted
    /// proxies. Passed to the backend, which limits what one source may open or attempt.
    pub source: Option<String>,
    /// The origin the request was made from, when it is one of the site's own. A passkey is made
    /// and used at that address.
    pub origin: Option<String>,
    /// The browser's `Idempotency-Key`, checked once by `visit`. Every call to the backend that
    /// this visit makes carries it, so that a change a retried request repeats is made once
    /// (OPS-318); a call that reads ignores it.
    pub idempotency_key: Option<String>,
}

fn text(headers: &HeaderMap, name: impl axum::http::header::AsHeaderName) -> Option<&str> {
    headers.get(name).and_then(|value| value.to_str().ok())
}

/// The cookie that holds the nonce binding an emailed link to the browser that asked for it.
const LINK_COOKIE: &str = "__Host-strata-link";
/// The cookie that holds the nonce binding a sign-in at an identity provider to the browser that
/// started it.
const OIDC_COOKIE: &str = "__Host-strata-oidc";
/// The same for a sign-in at a SAML provider.
const SAML_COOKIE: &str = "__Host-strata-saml";
/// The cookie that holds where to go after a sign-in at an identity provider. It is a path on this
/// site and nothing secret, and it is `Lax` because the provider's redirect back is a navigation
/// from another site, which a `Strict` cookie does not accompany. For a SAML provider the way back
/// is a POST, which a `Lax` cookie does not accompany either, so that one is `None`: it holds a
/// path and nothing else.
const RETURN_COOKIE: &str = "__Host-strata-return";

/// The value of a cookie that holds a nonce, when the browser holds a well-formed one.
fn binding_of(headers: &HeaderMap, name: &str) -> Option<String> {
    cookie_value(headers, name)
        .filter(|value| value.len() == 64 && value.chars().all(|c| c.is_ascii_hexdigit()))
}

/// The nonce in the link cookie, when the browser holds a well-formed one.
fn link_binding(headers: &HeaderMap) -> Option<String> {
    binding_of(headers, LINK_COOKIE)
}

/// A cookie as `__Host-` requires: `Secure`, `Path=/` and no `Domain`, and `HttpOnly`, so that a
/// page script cannot read it.
fn host_cookie(name: &str, value: &str, max_age: i64, same_site: &str) -> HeaderValue {
    HeaderValue::from_str(&format!(
        "{name}={value}; Path=/; Secure; HttpOnly; SameSite={same_site}; Max-Age={max_age}"
    ))
    .expect("cookie values are ASCII")
}

/// The link cookie: `Strict`, so that a link opened from another site does not carry it.
fn link_cookie(binding: &str, max_age: i64) -> HeaderValue {
    host_cookie(LINK_COOKIE, binding, max_age, "Strict")
}

/// The value of a cookie, as sent.
fn cookie_value(headers: &HeaderMap, name: &str) -> Option<String> {
    text(headers, COOKIE_HEADER)?
        .split(';')
        .filter_map(|pair| pair.trim().split_once('='))
        .find(|(cookie_name, _)| *cookie_name == name)
        .map(|(_, value)| value.to_string())
}

/// Percent-encode a value for a query string, a fragment or a cookie.
fn percent_encode(value: &str) -> String {
    value
        .bytes()
        .map(|b| {
            if b.is_ascii_alphanumeric() || matches!(b, b'-' | b'_' | b'.' | b'~') {
                (b as char).to_string()
            } else {
                format!("%{b:02X}")
            }
        })
        .collect()
}

/// A return address that is a path on this site: one slash first, no other host, no backslash
/// (which browsers read as a slash) and no control character (FED-250).
fn safe_path(path: &str) -> bool {
    path.len() <= 512
        && path.starts_with('/')
        && !path.starts_with("//")
        && !path.contains('\\')
        && !path.chars().any(char::is_control)
}

pub fn cookie(headers: &HeaderMap) -> Option<String> {
    text(headers, COOKIE_HEADER)?
        .split(';')
        .filter_map(|pair| pair.trim().split_once('='))
        .find(|(name, _)| *name == COOKIE)
        .map(|(_, value)| value.to_string())
        .filter(|value| value.len() == 64 && value.chars().all(|c| c.is_ascii_hexdigit()))
}

fn random_id(prefix: &str) -> String {
    let mut bytes = [0u8; 6];
    let _ = getrandom::getrandom(&mut bytes);
    format!(
        "{prefix}-{}",
        bytes.iter().map(|b| format!("{b:02x}")).collect::<String>()
    )
}

/// The host name of a request, without its port.
fn host_name(headers: &HeaderMap) -> &str {
    let host = text(headers, HOST).unwrap_or("");
    match host.rsplit_once(':') {
        Some((name, port)) if !port.is_empty() && port.chars().all(|c| c.is_ascii_digit()) => name,
        _ => host,
    }
}

/// Establish site, session token and correlation id. The site comes from the host name and this
/// process's configuration only.
pub fn visit(bff: &Bff, headers: &HeaderMap) -> Result<Visit, Failure> {
    let correlation = text(headers, HEADER_CORRELATION)
        .filter(|id| valid_correlation(id))
        .map(str::to_string)
        .unwrap_or_else(|| random_id("f"));
    let site = bff.site_of(host_name(headers)).ok_or_else(|| {
        Failure::new(
            ErrorCode::NotFound,
            "No site is served at this address.",
            &correlation,
        )
    })?;
    let origin = origin_allowed(bff, &site, headers)
        .then(|| text(headers, ORIGIN).map(str::to_string))
        .flatten();
    // The one check of the key's format at the edge: a key that cannot be used is refused, not
    // dropped, so that a change is never made without the protection the caller asked for.
    let idempotency_key = match headers.get(HEADER_IDEMPOTENCY) {
        None => None,
        Some(value) => Some(
            value
                .to_str()
                .ok()
                .filter(|key| valid_idempotency_key(key))
                .map(str::to_string)
                .ok_or_else(|| {
                    Failure::new(
                        ErrorCode::Invalid,
                        "An idempotency key is 1 to 128 visible ASCII characters.",
                        &correlation,
                    )
                })?,
        ),
    };
    Ok(Visit {
        idempotency_key,
        site,
        token: cookie(headers),
        correlation,
        // `envelope` replaces this header on every request, so it is never the browser's.
        source: text(headers, HEADER_SOURCE).map(str::to_string),
        origin,
    })
}

/// The site an origin such as `http://tidewater.localhost:4100` belongs to: the tenant its host
/// name serves.
fn origin_site(bff: &Bff, origin: &str) -> Option<TenantId> {
    let authority = origin.split_once("://")?.1;
    let authority = authority.split('/').next().unwrap_or(authority);
    let host = match authority.rsplit_once(':') {
        Some((name, port)) if !port.is_empty() && port.chars().all(|c| c.is_ascii_digit()) => name,
        _ => authority,
    };
    bff.site_of(host)
}

/// Whether the request's `Origin` is one of ours, and one of the site being served. Browsers send
/// it on every cross-origin request and on every same-origin request that is not a plain GET. An
/// origin of another site this process serves is not accepted: each site's pages act on that
/// site only.
pub fn origin_allowed(bff: &Bff, site: &TenantId, headers: &HeaderMap) -> bool {
    text(headers, ORIGIN).is_some_and(|origin| {
        bff.origins().iter().any(|allowed| allowed == origin)
            && origin_site(bff, origin).as_ref() == Some(site)
    })
}

/// Call the backend's internal API as this visit.
///
/// Implements: H-007
pub async fn backend<T: DeserializeOwned>(
    bff: &Bff,
    visit: &Visit,
    path: &str,
    body: &Json_,
) -> Result<T, Failure> {
    // The visit's idempotency key goes along: the backend scopes it by tenant and principal and
    // answers a repeat with the first result (OPS-318).
    let idempotency_key = visit.idempotency_key.as_deref();
    let unavailable = |why: String| {
        LOG.error(
            "backend.unreachable",
            &visit.correlation,
            json!({ "path": path, "error": why }),
        );
        Failure::new(
            ErrorCode::Unavailable,
            "The service is not available right now.",
            &visit.correlation,
        )
    };
    let mut request = bff
        .http
        .post(format!("{}{path}", bff.cfg.backend))
        .header(HEADER_SERVICE, &bff.cfg.service_token)
        .header(HEADER_SITE, visit.site.as_str())
        .header(HEADER_CORRELATION, &visit.correlation)
        .json(body);
    if let Some(token) = &visit.token {
        request = request.header(HEADER_SESSION, token);
    }
    if let Some(source) = &visit.source {
        request = request.header(HEADER_SOURCE, source);
    }
    if let Some(origin) = &visit.origin {
        request = request.header(HEADER_ORIGIN, origin);
    }
    if let Some(key) = idempotency_key {
        request = request.header(HEADER_IDEMPOTENCY, key);
    }
    let response = request
        .send()
        .await
        .map_err(|e| unavailable(e.to_string()))?;
    if response.status().is_success() {
        response
            .json::<T>()
            .await
            .map_err(|e| unavailable(e.to_string()))
    } else {
        let mut reply = response
            .json::<ErrorReply>()
            .await
            .map_err(|e| unavailable(e.to_string()))?;
        reply.correlation = visit.correlation.clone();
        Err(Failure(reply))
    }
}

/// The session cookie, as `__Host-` requires: `Secure`, `Path=/` and no `Domain`. Browsers treat
/// `http://localhost` and `http://127.0.0.1` as secure contexts and accept it there.
/// Implements: H-006
fn session_cookie(token: &str, max_age: i64) -> HeaderValue {
    HeaderValue::from_str(&format!(
        "{COOKIE}={token}; Path=/; Secure; HttpOnly; SameSite=Strict; Max-Age={max_age}"
    ))
    .expect("cookie values are ASCII")
}

/// A session as the browser may see it. A visitor with no session is handed a request token that
/// this process issued for the site, which is what the browser presents to sign in or to open a
/// socket.
fn with_request_token(bff: &Bff, visit: &Visit, mut session: SessionView) -> SessionView {
    if session.csrf_token.is_none() {
        session.csrf_token = Some(
            bff.tokens
                .issue(visit.site.as_str(), strata_protocol::log::now_ms()),
        );
    }
    session
}

/// Check the request token a request presents against the one its session has: the session's own
/// token when it is signed in, otherwise a token this process issued for the site. Returns `None`
/// when the token is missing or wrong, and otherwise whether the session is a live one.
async fn presented_token(bff: &Bff, visit: &Visit, given: &str) -> Result<Option<bool>, Failure> {
    let reply: SessionReply = backend(bff, visit, "/internal/session", &json!({})).await?;
    Ok(match &reply.session.csrf_token {
        Some(expected) => same(given, expected).then_some(true),
        None => bff
            .tokens
            .check(visit.site.as_str(), given, strata_protocol::log::now_ms())
            .then_some(false),
    })
}

/// Require the request to come from one of our pages and to carry the request token of its
/// session, whether or not there is a session yet. Returns whether the session is live.
async fn guard_request(bff: &Bff, visit: &Visit, headers: &HeaderMap) -> Result<bool, Failure> {
    let refuse = |message| Failure::new(ErrorCode::Forbidden, message, &visit.correlation);
    if !origin_allowed(bff, &visit.site, headers) {
        LOG.warn(
            "csrf.origin_refused",
            &visit.correlation,
            json!({ "origin": text(headers, ORIGIN) }),
        );
        return Err(refuse("This request did not come from the site."));
    }
    match presented_token(bff, visit, text(headers, "x-csrf-token").unwrap_or("")).await? {
        Some(live) => Ok(live),
        None => {
            LOG.warn("csrf.token_refused", &visit.correlation, json!({}));
            Err(refuse(
                "The request token is missing or stale. Reload the page and try again.",
            ))
        }
    }
}

/// Require a state-changing request to come from our own pages with the session's CSRF token.
async fn guard_write(
    bff: &Bff,
    visit: &Visit,
    headers: &HeaderMap,
) -> Result<SessionView, Failure> {
    let refuse = |message| Failure::new(ErrorCode::Forbidden, message, &visit.correlation);
    if !origin_allowed(bff, &visit.site, headers) {
        LOG.warn(
            "csrf.origin_refused",
            &visit.correlation,
            json!({ "origin": text(headers, ORIGIN) }),
        );
        return Err(refuse("This request did not come from the site."));
    }
    let reply: SessionReply = backend(bff, visit, "/internal/session", &json!({})).await?;
    let Some(expected) = &reply.session.csrf_token else {
        return Err(Failure::new(
            ErrorCode::Unauthenticated,
            "Sign in to do this.",
            &visit.correlation,
        ));
    };
    let given = text(headers, "x-csrf-token").unwrap_or("");
    if !same(given, expected) {
        LOG.warn("csrf.token_refused", &visit.correlation, json!({}));
        return Err(refuse(
            "The request token is missing or stale. Reload the page and try again.",
        ));
    }
    Ok(reply.session)
}

async fn session(State(bff): State<Shared>, headers: HeaderMap) -> Result<Response, Failure> {
    let visit = visit(&bff, &headers)?;
    let reply: SessionReply = backend(&bff, &visit, "/internal/session", &json!({})).await?;
    let mut response = Json(json!({
        "session": with_request_token(&bff, &visit, reply.session),
        "state": reply.state,
    }))
    .into_response();
    if visit.token.is_some() && matches!(reply.state, SessionState::Expired | SessionState::Revoked)
    {
        response
            .headers_mut()
            .insert(SET_COOKIE, session_cookie("", 0));
    }
    Ok(response)
}

/// Sign in with the named method: the same origin and request-token checks for every method,
/// the method's own credentials, and the session cookie from the backend's answer.
async fn sign_in(
    bff: &Bff,
    headers: &HeaderMap,
    method: &str,
    body: Json_,
) -> Result<Response, Failure> {
    let visit = visit(bff, headers)?;
    guard_request(bff, &visit, headers).await?;
    let route = signin::route(method).ok_or_else(|| {
        Failure::new(
            ErrorCode::NotFound,
            "No such sign-in method.",
            &visit.correlation,
        )
    })?;
    let binding = match method {
        "oidc" => binding_of(headers, OIDC_COOKIE),
        "saml" => binding_of(headers, SAML_COOKIE),
        _ => link_binding(headers),
    };
    let credentials = route
        .credentials(&body, binding.as_deref())
        .ok_or_else(|| {
            Failure::new(
                ErrorCode::Unauthenticated,
                route.refusal(),
                &visit.correlation,
            )
        })?;
    let reply: Json_ = backend(
        bff,
        &visit,
        &format!("/internal/session/sign-in/{method}"),
        &credentials,
    )
    .await?;
    finish_sign_in(&visit, reply)
}

/// What a sign-in answers. A first factor that is not enough yields no session and no cookie, only
/// the waiting sign-in the browser answers with its second factor. A session's token goes in the
/// cookie and nowhere else.
fn finish_sign_in(visit: &Visit, reply: Json_) -> Result<Response, Failure> {
    if let Some(waiting) = reply.get("second_factor") {
        return Ok(Json(json!({ "second_factor": waiting, "state": "pending" })).into_response());
    }
    let reply: LoginReply = serde_json::from_value(reply).map_err(|e| {
        LOG.error(
            "backend.unreadable",
            &visit.correlation,
            json!({ "path": "sign-in", "error": e.to_string() }),
        );
        Failure::new(
            ErrorCode::Unavailable,
            "The service is not available right now.",
            &visit.correlation,
        )
    })?;
    let lifetime = reply
        .session
        .expires_at
        .map_or(0, |at| (at - strata_protocol::log::now_ms()) / 1000)
        .max(0);
    let mut response = Json(json!({ "session": reply.session, "state": "active" })).into_response();
    response
        .headers_mut()
        .insert(SET_COOKIE, session_cookie(&reply.token, lifetime));
    Ok(response)
}

/// Give the second factor of a waiting sign-in, from one of the site's own pages and with the
/// request token every sign-in carries. Only the fields of a second factor go on to the backend. A
/// right one answers like a sign-in: the session's cookie.
async fn second_factor(
    State(bff): State<Shared>,
    headers: HeaderMap,
    Json(body): Json<Json_>,
) -> Result<Response, Failure> {
    let visit = visit(&bff, &headers)?;
    guard_request(&bff, &visit, &headers).await?;
    let sent = json!({
        "challenge": body.get("challenge"),
        "factor": body.get("factor"),
        "code": body.get("code"),
        "passkey_challenge": body.get("passkey_challenge"),
        "assertion": body.get("assertion"),
    });
    let reply: Json_ = backend(&bff, &visit, "/internal/session/second-factor", &sent).await?;
    finish_sign_in(&visit, reply)
}

