/// The origin published for a site: among the configured origins that serve it, an `https` one
/// before any other, and otherwise the first in alphabetical order, whatever order they were
/// listed in.
pub fn primary_origin(bff: &Bff, site: &TenantId) -> Option<String> {
    bff.origins()
        .into_iter()
        .filter(|origin| origin_site(bff, origin).as_ref() == Some(site))
        .min_by_key(|origin| (!origin.starts_with("https://"), origin.clone()))
}

async fn logout(State(bff): State<Shared>, headers: HeaderMap) -> Result<Response, Failure> {
    let visit = visit(&bff, &headers)?;
    // The token is required whether or not there is a session to end: the session's own when
    // there is one, the one this process issued to the browser when there is not.
    let live = guard_request(&bff, &visit, &headers).await?;
    // The cookie is cleared even when the backend cannot be reached: the browser must be able to
    // leave, and the session then ends by its own expiry.
    let cleared = |failure: Failure| {
        let mut response = failure.into_response();
        response
            .headers_mut()
            .insert(SET_COOKIE, session_cookie("", 0));
        response
    };
    if live {
        let ended: Result<Json_, Failure> =
            backend(&bff, &visit, "/internal/session/logout", &json!({})).await;
        if let Err(failure) = ended {
            return Ok(cleared(failure));
        }
    }
    let anonymous = Visit {
        token: None,
        ..visit
    };
    let reply: SessionReply = match backend(&bff, &anonymous, "/internal/session", &json!({})).await
    {
        Ok(reply) => reply,
        Err(failure) => return Ok(cleared(failure)),
    };
    let mut response = Json(json!({
        "session": with_request_token(&bff, &anonymous, reply.session),
        "state": "anonymous",
    }))
    .into_response();
    response
        .headers_mut()
        .insert(SET_COOKIE, session_cookie("", 0));
    Ok(response)
}

/// What a view request asks beyond the path and the request map (CMS-163, CMS-164): the fields to
/// keep, the cursor of one section's next page and the size of a page.
#[derive(Default)]
struct Paging {
    fields: Option<Vec<String>>,
    cursor: Option<String>,
    limit: Option<u32>,
}

/// Fetch a view from the backend and project it into the browser's view model.
async fn view_model(
    bff: &Bff,
    visit: &Visit,
    path: &str,
    request: BTreeMap<String, String>,
    paging: Paging,
) -> Result<Json_, Failure> {
    let data: ViewData = backend(
        bff,
        visit,
        "/internal/view",
        &json!(ViewRequest {
            path: path.to_string(),
            request,
            fields: paging.fields,
            cursor: paging.cursor,
            limit: paging.limit,
        }),
    )
    .await?;
    let mut model = project(&data);
    let settings = data
        .sections
        .get("site")
        .and_then(|section| section.rows.first());
    let (resolved, rejected) = settings
        .map(|record| theme::resolve(&record.fields))
        .unwrap_or_default();
    if !rejected.is_empty() {
        LOG.warn(
            "theme.rejected",
            &visit.correlation,
            json!({ "settings": rejected }),
        );
    }
    model["theme"] = json!(resolved);
    model["path"] = json!(path);
    if let Some(info) = screens::view_info(data.view.as_str()) {
        // The outputs the screen's view model states beyond the sections (for the writing desk:
        // each article as its per-row actions name it, the topic and author choices, the record
        // a save starts from, the names a swatch can take).
        derive_outputs(&mut model, info);
    }
    Ok(model)
}

/// The value at a dotted path of a record; null when there is none.
fn at_path<'a>(value: &'a Json_, path: &str) -> &'a Json_ {
    path.split('.').fold(value, |at, key| &at[key])
}

/// Add the outputs a view's screen states (`viewOutputs` of the specification), in order.
fn derive_outputs(model: &mut Json_, info: &screens::ViewInfo) {
    for output in info.outputs {
        let value = match output.kind {
            "rows" => {
                let rows = model["data"][output.from]
                    .as_array()
                    .cloned()
                    .unwrap_or_default();
                Some(json!(rows
                    .iter()
                    .map(|row| {
                        let item: serde_json::Map<String, Json_> = output
                            .args
                            .iter()
                            .map(|(name, path)| ((*name).to_string(), at_path(row, path).clone()))
                            .collect();
                        Json_::Object(item)
                    })
                    .collect::<Vec<_>>()))
            }
            "choices" => {
                let leading = output
                    .args
                    .iter()
                    .find(|(name, _)| *name == "leading-label")
                    .map(|(_, label)| json!({ "value": "", "label": label }));
                Some(json!(leading
                    .into_iter()
                    .chain(choices(&model["data"][output.from]))
                    .collect::<Vec<_>>()))
            }
            "copy" => {
                let (section, rest) = output.from.split_once('.').unwrap_or((output.from, ""));
                let root = &model["data"][section];
                root.is_object().then(|| at_path(root, rest).clone())
            }
            "theme-names" => match output.from {
                "accents" => Some(json!(theme::ACCENTS)),
                "papers" => Some(json!(theme::PAPERS)),
                _ => None,
            },
            _ => None,
        };
        if let Some(value) = value {
            model[output.output] = value;
        }
    }
}

/// A page title as the specification states it: its text, with the parts read from the view model.
fn title_text(model: &Json_, parts: &[screens::TitlePart]) -> String {
    parts
        .iter()
        .map(|part| match part {
            screens::TitlePart::Text(text) => (*text).to_string(),
            screens::TitlePart::Path(path) => match path.iter().fold(model, |at, key| &at[*key]) {
                Json_::String(text) => text.clone(),
                Json_::Number(number) => number.to_string(),
                _ => String::new(),
            },
        })
        .collect()
}

/// One choice per row of a projected section: the record's identifier as text and its name.
fn choices(rows: &Json_) -> Vec<Json_> {
    rows.as_array()
        .map(|rows| {
            rows.iter()
                .map(|row| {
                    let value = match &row["id"] {
                        Json_::String(id) => id.clone(),
                        other => other.to_string(),
                    };
                    json!({ "value": value, "label": row["fields"]["name"] })
                })
                .collect()
        })
        .unwrap_or_default()
}

async fn view(
    State(bff): State<Shared>,
    headers: HeaderMap,
    Query(mut query): Query<BTreeMap<String, String>>,
) -> Result<Json<Json_>, Failure> {
    let visit = visit(&bff, &headers)?;
    let path = query
        .remove("path")
        .filter(|p| p.starts_with('/') && p.len() <= 300)
        .unwrap_or_else(|| "/".into());
    // `fields`, `cursor` and `limit` are the delivery interface's own (CMS-163, CMS-164) and are
    // never a view's request parameters. The backend checks the names against the view's fields.
    let refuse = |why: &str| Failure::new(ErrorCode::Invalid, why, &visit.correlation);
    let fields = match query.remove("fields") {
        Some(list) if list.len() <= 2000 => Some(list.split(',').map(str::to_string).collect()),
        Some(_) => return Err(refuse("The field selection is too long.")),
        None => None,
    };
    let limit = match query.remove("limit") {
        Some(text) => Some(
            text.parse::<u32>()
                .map_err(|_| refuse("A limit is a whole number."))?,
        ),
        None => None,
    };
    let cursor = match query.remove("cursor") {
        Some(text) if text.len() <= 200 => Some(text),
        Some(_) => return Err(refuse("The cursor is not one this view issued.")),
        None => None,
    };
    query.retain(|name, value| name.len() <= 32 && value.len() <= 200);
    let paging = Paging {
        fields,
        cursor,
        limit,
    };
    view_model(&bff, &visit, &path, query, paging)
        .await
        .map(Json)
}

/// Run one aggregate of a named query: `GET /api/aggregate?query=&aggregate=&filter=`, the filter
/// being a JSON object of field values. The backend's kernel decides what the reader may count.
///
/// Implements: CT-310
async fn aggregate_run(
    State(bff): State<Shared>,
    headers: HeaderMap,
    Query(mut query): Query<BTreeMap<String, String>>,
) -> Result<Json<Json_>, Failure> {
    let visit = visit(&bff, &headers)?;
    let invalid = |why: &str| Failure::new(ErrorCode::Invalid, why, &visit.correlation);
    let name = |query: &mut BTreeMap<String, String>, key: &str| {
        query
            .remove(key)
            .filter(|value| !value.is_empty() && value.len() <= 64)
    };
    let (Some(wanted), Some(aggregate)) =
        (name(&mut query, "query"), name(&mut query, "aggregate"))
    else {
        return Err(invalid(
            "An aggregate request names a query and an aggregate.",
        ));
    };
    let filter = match query.remove("filter") {
        None => serde_json::Map::new(),
        Some(text) if text.len() <= 2_000 => match serde_json::from_str::<Json_>(&text) {
            Ok(Json_::Object(map)) => map,
            _ => return Err(invalid("The filter is a JSON object of field values.")),
        },
        Some(_) => return Err(invalid("The filter is too long.")),
    };
    let request = strata_protocol::api::AggregateRunRequest {
        query: wanted,
        aggregate,
        filter,
    };
    backend(&bff, &visit, "/internal/aggregate", &json!(request))
        .await
        .map(Json)
}

