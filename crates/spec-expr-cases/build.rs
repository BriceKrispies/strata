//! Compiles every case of the shared case table (`cases.json`, a byte-identical copy of Exegra's
//! `tests/fixtures/expr-cases.json`) through `strata-spec-expr`:
//!
//! - to Rust: `$OUT_DIR/cases.rs`, one function per case that decodes the case's environment into a
//!   struct of its declared types (serde, as generated payloads and records are decoded: a missing
//!   `Option` is `None`, any other missing field refuses the decode) and evaluates the translated
//!   expression;
//! - to JavaScript: `$OUT_DIR/cases.mjs`, a node script that does the same with the translated
//!   JavaScript and prints every outcome as JSON.
//!
//! An expression the translation refuses becomes the outcome `refused`.

use proc_macro2::TokenStream;
use quote::{format_ident, quote};
use serde_json::Value;
use std::collections::BTreeMap;
use std::fmt::Write as _;
use std::path::PathBuf;
use strata_spec_expr::{Binding, JsBinding, JsScope, Scope, Ty};

/// The expression type of a type name of the table, as specc's machines see it: a timestamp is
/// read as its `i64` milliseconds, a duration as `u64`.
fn ty_of(name: &str) -> Ty {
    let name = name.trim();
    if let Some(inner) = name
        .strip_prefix("option<")
        .and_then(|s| s.strip_suffix('>'))
    {
        return Ty::Option(Box::new(ty_of(inner)));
    }
    if let Some(inner) = name.strip_prefix("list<").and_then(|s| s.strip_suffix('>')) {
        return Ty::List(Box::new(ty_of(inner)));
    }
    match name {
        "bool" => Ty::Bool,
        "u8" => Ty::U8,
        "u16" => Ty::U16,
        "u32" => Ty::U32,
        "u64" => Ty::U64,
        "i32" => Ty::I32,
        "i64" | "timestamp" => Ty::I64,
        "duration" => Ty::U64,
        "f64" => Ty::F64,
        "string" => Ty::String,
        "json" => Ty::Json,
        other => Ty::Named(other.to_string()),
    }
}

/// The Rust type a value of `ty` is decoded into.
fn rust_ty(ty: &Ty) -> TokenStream {
    match ty {
        Ty::Bool => quote!(bool),
        Ty::U8 => quote!(u8),
        Ty::U16 => quote!(u16),
        Ty::U32 => quote!(u32),
        Ty::U64 => quote!(u64),
        Ty::I32 => quote!(i32),
        Ty::I64 => quote!(i64),
        Ty::F64 => quote!(f64),
        Ty::String => quote!(::std::string::String),
        Ty::Json => quote!(::serde_json::Value),
        Ty::Option(t) => {
            let t = rust_ty(t);
            quote!(::core::option::Option<#t>)
        }
        Ty::List(t) => {
            let t = rust_ty(t);
            quote!(::std::vec::Vec<#t>)
        }
        Ty::Named(n) if n == "point" => quote!(crate::Point),
        other => panic!("type {other} has no decoding in the case harness"),
    }
}

fn field_name(path: &str) -> String {
    format!("r_{}", path.replace(['.', '-'], "_"))
}

struct CaseScope {
    types: BTreeMap<String, Ty>,
}

impl Scope for CaseScope {
    fn resolve(&self, path: &[&str]) -> Option<Binding> {
        let key = path.join(".");
        let ty = self.types.get(&key)?.clone();
        let field = format_ident!("{}", field_name(&key));
        Some(Binding {
            ty,
            tokens: quote!(env.#field),
        })
    }

    fn overflow_error(&self) -> TokenStream {
        quote!(crate::StepError)
    }
}

impl JsScope for CaseScope {
    fn resolve_js(&self, path: &[&str]) -> Option<JsBinding> {
        let key = path.join(".");
        let ty = self.types.get(&key)?.clone();
        Some(JsBinding {
            ty,
            js: field_name(&key),
        })
    }

    fn overflow_error_js(&self) -> String {
        "__ov()".to_string()
    }
}

fn main() {
    let dir = PathBuf::from(std::env::var("CARGO_MANIFEST_DIR").unwrap());
    let table_path = dir.join("cases.json");
    println!("cargo:rerun-if-changed={}", table_path.display());
    let table: Value =
        serde_json::from_str(&std::fs::read_to_string(&table_path).unwrap()).unwrap();
    let mut cases = table["cases"].as_array().expect("cases").clone();
    // The cases only the Strata targets run, after the shared ones.
    let extra_path = dir.join("cases-strata.json");
    println!("cargo:rerun-if-changed={}", extra_path.display());
    let extra: Value =
        serde_json::from_str(&std::fs::read_to_string(&extra_path).unwrap()).unwrap();
    cases.extend(
        extra["cases"]
            .as_array()
            .expect("cases of the extra table")
            .clone(),
    );

    let mut rust_items: Vec<TokenStream> = Vec::new();
    let mut arms: Vec<TokenStream> = Vec::new();
    let mut js = String::new();
    js.push_str("// @generated by crates/spec-expr-cases/build.rs from cases.json.\n");
    js.push_str("class Overflow extends Error {}\nfunction __ov() { throw new Overflow('overflow'); }\nclass Absent extends Error {}\n");
    js.push_str("const out = [];\n");

    for (i, c) in cases.iter().enumerate() {
        let src = c["expr"].as_str().expect("expr");
        let types: BTreeMap<String, Ty> = c["types"]
            .as_object()
            .expect("types")
            .iter()
            .map(|(k, v)| (k.clone(), ty_of(v.as_str().expect("type name"))))
            .collect();
        let scope = CaseScope {
            types: types.clone(),
        };
        let parsed =
            strata_spec_expr::parse(src).unwrap_or_else(|e| panic!("case {i} `{src}`: {e}"));
        let env_struct = format_ident!("Env{}", i);
        let fun = format_ident!("case_{}", i);

        // Rust.
        let fields: Vec<TokenStream> = types
            .iter()
            .map(|(k, t)| {
                let f = format_ident!("{}", field_name(k));
                let rt = rust_ty(t);
                quote! {
                    #[serde(rename = #k)]
                    #f: #rt
                }
            })
            .collect();
        let body = match strata_spec_expr::to_rust(&parsed, &scope) {
            Ok(tokens) => quote! {
                let env: #env_struct = match ::serde_json::from_value(env) {
                    ::core::result::Result::Ok(e) => e,
                    ::core::result::Result::Err(_) => return crate::Outcome::Absent,
                };
                let run = || -> ::core::result::Result<_, crate::StepError> {
                    ::core::result::Result::Ok(#tokens)
                };
                match run() {
                    ::core::result::Result::Ok(v) => crate::Outcome::Value(::serde_json::to_value(v).unwrap()),
                    ::core::result::Result::Err(_) => crate::Outcome::Overflow,
                }
            },
            Err(_) => quote! {
                let _ = env;
                crate::Outcome::Refused
            },
        };
        rust_items.push(quote! {
            #[derive(::serde::Deserialize)]
            #[allow(dead_code, non_snake_case)]
            struct #env_struct {
                #(#fields),*
            }
            #[allow(unused_variables, clippy::all)]
            fn #fun(env: ::serde_json::Value) -> crate::Outcome {
                #body
            }
        });
        arms.push(quote!(#i => #fun(env),));

        // JavaScript.
        let _ = write!(js, "out.push((() => {{ const env = {}; try {{ ", c["env"]);
        for (k, t) in &types {
            let key = serde_json::to_string(k).unwrap();
            let f = field_name(k);
            if matches!(t, Ty::Option(_)) {
                let _ = write!(js, "const {f} = env[{key}] ?? null; ");
            } else {
                let _ = write!(
                    js,
                    "if (!Object.hasOwn(env, {key})) throw new Absent(); const {f} = env[{key}]; "
                );
            }
        }
        match strata_spec_expr::to_js(&parsed, &scope) {
            Ok(code) => {
                let _ = write!(js, "return {{ value: ({code}) }}; ");
            }
            Err(_) => {
                js.push_str("return { error: 'refused' }; ");
            }
        }
        js.push_str("} catch (e) { if (e instanceof Overflow) return { error: 'overflow' }; if (e instanceof Absent) return { error: 'absent' }; return { error: `unexpected: ${e}` }; } })());\n");
    }
    js.push_str("console.log(JSON.stringify(out));\n");

    let n = cases.len();
    let rust = quote! {
        /// The number of cases.
        pub const CASES: usize = #n;
        #(#rust_items)*
        /// Run case `i` on its environment.
        pub fn run(i: usize, env: ::serde_json::Value) -> crate::Outcome {
            match i {
                #(#arms)*
                _ => panic!("no case {i}"),
            }
        }
    };
    let out = PathBuf::from(std::env::var("OUT_DIR").unwrap());
    std::fs::write(out.join("cases.rs"), rust.to_string()).unwrap();
    std::fs::write(out.join("cases.mjs"), js).unwrap();
}
