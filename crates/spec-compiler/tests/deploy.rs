//! The deployment output: a golden fixture (`tests/fixtures/deploy/expected`, rewritten by
//! `SPECC_BLESS=1`), the exactness of the generated network policies against the declared
//! relationships, and the alert rules read from budget statements.

use std::collections::{BTreeMap, BTreeSet};
use std::fs;
use std::path::PathBuf;

use strata_spec_compiler::deploy::{self, CONNECTING_KINDS, UNIT_CATEGORIES};
use strata_spec_compiler::{output, GeneratedFile};

const FIXTURE_SPEC: &str = "crates/spec-compiler/tests/fixtures/deploy/spec.jsonc";

fn manifest_dir() -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR"))
}

fn fixture_text() -> String {
    fs::read_to_string(manifest_dir().join("tests/fixtures/deploy/spec.jsonc")).unwrap()
}

fn fixture_files() -> Vec<GeneratedFile> {
    deploy::generate(FIXTURE_SPEC, &fixture_text())
        .unwrap()
        .files
}

fn contents<'a>(files: &'a [GeneratedFile], path: &str) -> &'a str {
    &files
        .iter()
        .find(|f| f.path == path)
        .unwrap_or_else(|| panic!("no file {path}"))
        .contents
}

#[test]
fn golden_output_matches_the_expected_files() {
    let dir = manifest_dir().join("tests/fixtures/deploy/expected");
    let files = fixture_files();
    if std::env::var("SPECC_BLESS").as_deref() == Ok("1") {
        output::write(&dir, &files).unwrap();
        return;
    }
    let differences = output::compare(&dir, &files).unwrap();
    assert!(
        differences.is_empty(),
        "tests/fixtures/deploy/expected is not what specc deploy generates: {differences:?}. \
         Run the test with SPECC_BLESS=1 to rewrite it, and review the change."
    );
}

#[test]
fn every_file_has_the_header_and_generation_is_repeatable() {
    let files = fixture_files();
    assert_eq!(files, fixture_files());
    for file in &files {
        assert!(
            file.contents.starts_with(
                "# @generated by specc from crates/spec-compiler/tests/fixtures/deploy/spec.jsonc."
            ),
            "{} has no header",
            file.path
        );
    }
    let paths: Vec<&str> = files.iter().map(|f| f.path.as_str()).collect();
    assert_eq!(
        paths,
        [
            "compose.yaml",
            "kubernetes/data/telemetry.yaml",
            "kubernetes/data/tenant-db.yaml",
            "kubernetes/edge/gateway.yaml",
            "kubernetes/namespaces.yaml",
            "kubernetes/tenant/runtime.yaml",
            "kubernetes/tenant/worker.yaml",
            "monitoring/budget-alerts.yaml",
        ]
    );
}

/// The units named in the ingress rules of the NetworkPolicy in a unit's manifest file.
fn admitted(manifest: &str) -> BTreeSet<String> {
    let policy = manifest
        .split("\n---\n")
        .find(|doc| doc.contains("kind: NetworkPolicy"))
        .expect("a NetworkPolicy");
    let ingress = policy
        .split("  ingress:")
        .nth(1)
        .expect("an ingress section");
    ingress
        .lines()
        .filter_map(|l| l.trim().strip_prefix("app.kubernetes.io/name: "))
        .map(str::to_string)
        .collect()
}

/// The deployable components and, for each, the units that declare a connecting relationship
/// to it, computed without the compiler's own code.
fn declared(spec: &serde_json::Value) -> (Vec<String>, BTreeMap<String, BTreeSet<String>>) {
    let units: Vec<String> = spec["components"]
        .as_array()
        .unwrap()
        .iter()
        .filter(|c| UNIT_CATEGORIES.contains(&c["category"].as_str().unwrap_or("")))
        .map(|c| c["id"].as_str().unwrap().to_string())
        .collect();
    let mut into: BTreeMap<String, BTreeSet<String>> =
        units.iter().map(|u| (u.clone(), BTreeSet::new())).collect();
    for r in spec["relationships"].as_array().unwrap() {
        let (from, to) = (r["from"].as_str().unwrap(), r["to"].as_str().unwrap());
        if CONNECTING_KINDS.contains(&r["kind"].as_str().unwrap())
            && from != to
            && units.iter().any(|u| u == from)
        {
            if let Some(set) = into.get_mut(to) {
                set.insert(from.to_string());
            }
        }
    }
    (units, into)
}

fn check_policies(spec_text: &str, spec_path: &str) {
    let spec = strata_spec_compiler::jsonc::parse(spec_text).unwrap();
    let files = deploy::generate(spec_path, spec_text).unwrap().files;
    let (units, into) = declared(&spec);
    for unit in &units {
        let zone = spec["components"]
            .as_array()
            .unwrap()
            .iter()
            .find(|c| c["id"] == unit.as_str())
            .unwrap()["trustZone"]
            .as_str()
            .unwrap()
            .to_string();
        let manifest = contents(&files, &format!("kubernetes/{zone}/{unit}.yaml"));
        assert_eq!(&admitted(manifest), &into[unit], "policy of {unit}");
    }
}

#[test]
fn network_policies_admit_exactly_the_declared_relationships_of_the_fixture() {
    check_policies(&fixture_text(), FIXTURE_SPEC);
    let files = fixture_files();
    let runtime = contents(&files, "kubernetes/tenant/runtime.yaml");
    assert_eq!(
        admitted(runtime),
        BTreeSet::from(["gateway".to_string(), "worker".to_string()])
    );
    // `observes` and `depends-on` open nothing, and a client is not a unit.
    let gateway = contents(&files, "kubernetes/edge/gateway.yaml");
    assert!(admitted(gateway).is_empty());
    assert!(gateway.contains("ingress: []"));
}

#[test]
fn network_policies_admit_exactly_the_declared_relationships_of_the_specification() {
    let path = manifest_dir().join("../../specifications/spec.jsonc");
    let text = fs::read_to_string(path).unwrap();
    check_policies(&text, "specifications/spec.jsonc");
}

#[test]
fn compose_joins_only_the_networks_a_connection_needs() {
    let files = fixture_files();
    let compose = contents(&files, "compose.yaml");
    assert!(
        !compose.contains("  kernel:"),
        "a logical component is not a unit"
    );
    assert!(!compose.contains("  browser:"), "a client is not a unit");
    // Only implemented units are in the stack: the rest have no image.
    for absent in ["tenant-db", "telemetry", "worker"] {
        assert!(
            !compose.contains(&format!("  {absent}:")),
            "{absent} is not implemented"
        );
    }
    assert!(compose.contains("not implemented and have no image: tenant-db, telemetry, worker"));
    assert!(compose.contains("zone-tenant: {}"));
    assert!(
        !compose.contains("zone-data"),
        "no runnable unit connects into the data zone"
    );
    assert!(
        !compose.contains("zone-edge"),
        "nothing connects to the gateway"
    );
}

#[test]
fn a_profile_adds_build_environment_health_and_dependencies_to_the_units_it_configures() {
    let profile = r#"{
        "containerfile": "deploy/Containerfile",
        "context": "..",
        "units": {
            "runtime": {
                "port": 4101,
                "health": "/health",
                "env": { "TOKEN": "${TOKEN}" },
                "volumes": ["data:/var/lib/app"]
            },
            "gateway": {
                "port": 4100,
                "shareNetworkWith": "runtime",
                "publish": ["127.0.0.1:4100:4100"]
            }
        }
    }"#;
    let files = deploy::generate_with_profile(FIXTURE_SPEC, &fixture_text(), Some(profile))
        .unwrap()
        .files;
    let compose = contents(&files, "compose.yaml");
    assert!(compose.contains("target: \"runtime\""));
    assert!(compose.contains("TOKEN: \"${TOKEN}\""));
    assert!(compose.contains("\"/dev/null\", \"http://127.0.0.1:4101/health\""));
    assert!(compose.contains("network_mode: \"service:runtime\""));
    assert!(compose.contains("condition: service_healthy"));
    assert!(compose.contains("  data: {}"), "a named volume is declared");
    // The gateway's published port lives on the unit that owns the namespace.
    let runtime = compose
        .split("  runtime:")
        .nth(1)
        .unwrap()
        .split("  gateway:")
        .next()
        .unwrap();
    assert!(runtime.contains("127.0.0.1:4100:4100"));
    // A profile that names a unit the specification does not deploy is refused.
    let unknown = r#"{ "units": { "ghost": {} } }"#;
    let codes: Vec<String> =
        deploy::generate_with_profile(FIXTURE_SPEC, &fixture_text(), Some(unknown))
            .unwrap_err()
            .into_iter()
            .map(|d| d.code)
            .collect();
    assert_eq!(codes, ["deploy.profile-unit-unknown"]);
}

#[test]
fn budget_requirements_become_alert_rules_labelled_with_their_ref() {
    let files = fixture_files();
    let rules = contents(&files, "monitoring/budget-alerts.yaml");
    assert!(rules.contains("- alert: Budget_OPS_1"));
    assert!(rules.contains(
        "histogram_quantile(0.99, sum by (le) (rate(strata_b_2_commit_duration_seconds_bucket[5m]))) > 0.3"
    ));
    assert!(rules.contains("requirement: \"OPS-1\""));
    // A statement with no readable target keeps the placeholder and says so.
    assert!(rules.contains("- alert: Budget_OPS_2"));
    assert!(rules.contains("expr: \"strata_b_9_reply\""));
    assert!(rules.contains("threshold: \"unparsed\""));
    assert!(rules.contains("requirement: \"OPS-2\""));
    // A requirement checked another way has no rule.
    assert!(!rules.contains("OPS-3"));
}

#[test]
fn warnings_report_unimplemented_units_without_refusing() {
    let output = deploy::generate(FIXTURE_SPEC, &fixture_text()).unwrap();
    assert_eq!(output.warnings.len(), 1);
    assert!(output.warnings[0].contains("tenant-db, telemetry, worker"));
}

#[test]
fn a_relationship_to_an_unknown_component_is_refused() {
    let text = r#"{
        "components": [{"id":"a","category":"computational","trustZone":"z"}],
        "relationships": [{"id":"r","kind":"calls","from":"a","to":"ghost"}]
    }"#;
    let diagnostics = deploy::generate("s.jsonc", text).unwrap_err();
    assert_eq!(diagnostics.len(), 1);
    assert_eq!(
        diagnostics[0].to_string(),
        "error[deploy.relationship-endpoint-unknown] r: \"ghost\" is not a declared component."
    );
}

#[test]
fn a_unit_without_a_zone_or_with_a_bad_name_is_refused() {
    let text = r#"{
        "components": [
            {"id":"a","category":"computational"},
            {"id":"Bad_Name","category":"storage","trustZone":"z"}
        ]
    }"#;
    let codes: Vec<String> = deploy::generate("s.jsonc", text)
        .unwrap_err()
        .into_iter()
        .map(|d| d.code)
        .collect();
    assert_eq!(codes, ["deploy.zone-missing", "deploy.name-invalid"]);
}
