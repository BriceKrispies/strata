#[test]
fn faults_that_change_the_model_are_refused_before_exegra_runs() {
    let spec = edit(
        &spec_text(),
        "\"scenarios\": [",
        r#""faults": [
    { "id": "f-off", "kind": "disable-transition", "transition": "grant" },
    { "id": "f-on", "kind": "enable-transition", "transition": "grant" },
    { "id": "f-drop", "kind": "drop-event", "event": "lease-result" },
    { "id": "f-late", "kind": "delay-event", "event": "lease-result", "by": 5 }
  ],
  "scenarios": ["#,
    );
    let spec = edit(
        &spec,
        "\"behaviors\": [\"lease\"], \"timeUnit\"",
        "\"behaviors\": [\"lease\"], \"faults\": [\"f-off\", \"f-drop\", \"f-on\", \"f-late\"], \"timeUnit\"",
    );
    // No trace source: the unsupported faults are still named, the supported ones are not.
    let diagnostics = scenarios::generate(SPEC_PATH, &spec, CRATE, None).unwrap_err();
    let refused: Vec<&Diagnostic> = diagnostics
        .iter()
        .filter(|d| d.code == scenarios::FAULT_UNSUPPORTED)
        .collect();
    assert_eq!(refused.len(), 2);
    assert!(refused[0].message.contains("f-off") && refused[1].message.contains("f-on"));
    assert!(diagnostics.iter().all(|d| d.code != scenarios::NO_EXEGRA));
}

#[test]
fn drop_delay_and_inject_faults_are_replayed_from_the_trace() {
    let spec = edit(
        &spec_text(),
        "\"scenarios\": [",
        r#""faults": [
    { "id": "f-drop", "kind": "drop-event", "event": "lease-result", "occurrence": 1 },
    { "id": "f-late", "kind": "delay-event", "event": "lease-result", "by": 5 },
    { "id": "f-extra", "kind": "inject-event", "event": "lease-requested", "at": 2, "payload": { "holder": "w9" } }
  ],
  "scenarios": ["#,
    );
    let spec = edit(
        &spec,
        "\"behaviors\": [\"lease\"], \"timeUnit\"",
        "\"behaviors\": [\"lease\"], \"faults\": [\"f-drop\", \"f-late\", \"f-extra\"], \"timeUnit\"",
    );
    // A trace as Exegra records one with those faults: a dropped step, a delayed step, and the
    // events delivered at their shifted times.
    let mut trace = canned_trace();
    let steps = trace["steps"].as_array_mut().unwrap();
    let mut dropped = steps[1].clone();
    dropped["kind"] = json!("drop");
    dropped["fired"] = json!([]);
    dropped["faults"] = json!([{ "fault": "f-drop", "effect": "dropped" }]);
    steps[1] = dropped;
    let mut delayed = steps[2].clone();
    delayed["kind"] = json!("delay");
    delayed["fired"] = json!([]);
    delayed["faults"] = json!([{ "fault": "f-late", "effect": "delayed" }]);
    steps[2] = delayed;
    let text = generated(&spec, &trace).unwrap();
    assert!(text.contains("dropped by f-drop; nothing is delivered."));
    assert!(text.contains("delayed by f-late; nothing is delivered."));
}

