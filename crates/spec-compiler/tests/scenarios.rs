//! The scenario tests (`specc scenarios`): a golden over the machines fixture, built from a canned
//! Exegra trace (`tests/fixtures/machines/lease-run.trace.json`, written by
//! `node $EXEGRA_HOME/cli/exegra.js trace lease-run --project machines --specs tests/fixtures
//! --out ...`) so no Exegra is needed here; a check that every expected value in the generated
//! test comes from the trace, and so changes with it; the `Verifies:` lines; and the refusals.
//!
//! The golden, `tests/fixtures/machines/expected-scenarios.rs`, is rewritten by `SPECC_BLESS=1`.
//! It is also the file to copy into the fixture crate's `tests` directory (`specc scenarios
//! --spec ... --out crates/spec-compiler-machines-fixture/tests`), where it runs against the
//! generated lease.

use std::path::PathBuf;

use serde_json::{json, Value};
use strata_spec_compiler::scenarios;
use strata_spec_compiler::Diagnostic;

const SPEC_PATH: &str = "crates/spec-compiler/tests/fixtures/machines/spec.jsonc";
const CRATE: &str = "strata-spec-compiler-machines-fixture";

fn fixtures() -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("tests/fixtures/machines")
}

fn spec_text() -> String {
    std::fs::read_to_string(fixtures().join("spec.jsonc")).unwrap()
}

fn canned_trace() -> Value {
    let text = std::fs::read_to_string(fixtures().join("lease-run.trace.json")).unwrap();
    serde_json::from_str(&text).unwrap()
}

/// The text of `scenarios.rs` generated from `spec` and a trace.
fn generated(spec: &str, trace: &Value) -> Result<String, Vec<Diagnostic>> {
    let source = |_: &str| -> Result<Value, String> { Ok(trace.clone()) };
    scenarios::generate(SPEC_PATH, spec, CRATE, Some(&source)).map(|o| {
        assert_eq!(o.files.len(), 1);
        assert_eq!(o.files[0].path, "scenarios.rs");
        o.files[0].contents.clone()
    })
}

fn fixture_output() -> String {
    generated(&spec_text(), &canned_trace()).unwrap()
}

fn edit(text: &str, from: &str, to: &str) -> String {
    assert!(text.contains(from), "the fixture no longer contains {from}");
    text.replacen(from, to, 1)
}

fn codes(result: Result<String, Vec<Diagnostic>>) -> Vec<String> {
    result.unwrap_err().into_iter().map(|d| d.code).collect()
}

/// Steps of the trace that deliver an event the lease receives, with the lease's firing.
fn lease_deliveries(trace: &Value) -> Vec<&Value> {
    let events = ["lease-requested", "lease-result", "lease-expired"];
    trace["steps"]
        .as_array()
        .unwrap()
        .iter()
        .filter(|s| events.contains(&s["event"]["id"].as_str().unwrap()))
        .collect()
}

#[test]
fn golden_output_matches_the_expected_file() {
    let path = fixtures().join("expected-scenarios.rs");
    let text = fixture_output();
    if std::env::var("SPECC_BLESS").as_deref() == Ok("1") {
        std::fs::write(&path, &text).unwrap();
        return;
    }
    let expected = std::fs::read_to_string(&path).unwrap_or_else(|_| {
        panic!("tests/fixtures/machines/expected-scenarios.rs is missing. Run the test with SPECC_BLESS=1 to write it, and review it.")
    });
    assert_eq!(
        expected.replace("\r\n", "\n"),
        text,
        "tests/fixtures/machines/expected-scenarios.rs is not what specc scenarios generates. Run the test with SPECC_BLESS=1 to rewrite it, and review the change."
    );
}

#[test]
fn the_file_is_rust_with_one_test_per_scenario_and_is_repeatable() {
    let text = fixture_output();
    assert_eq!(text, fixture_output());
    assert!(text.starts_with(&format!(
        "// @generated by specc from {SPEC_PATH}. Do not edit; change the specification and regenerate.\n"
    )));
    let file = syn::parse_file(&text).expect("the generated file is not Rust");
    let tests: Vec<String> = file
        .items
        .iter()
        .filter_map(|i| match i {
            syn::Item::Fn(f) if f.attrs.iter().any(|a| a.path().is_ident("test")) => {
                Some(f.sig.ident.to_string())
            }
            _ => None,
        })
        .collect();
    // The fixture's only scenario that runs only implementation machines.
    assert_eq!(tests, ["scenario_lease_run"]);
    assert!(text.contains("use strata_spec_compiler_machines_fixture::machines::lease::Lease;"));
    assert!(!text.contains("::job::") && !text.contains("::hold::"));
}

#[test]
fn every_delivery_to_the_lease_is_a_call_and_every_value_is_the_traces() {
    let trace = canned_trace();
    let text = fixture_output();
    let deliveries = lease_deliveries(&trace);
    assert!(
        deliveries.len() >= 8,
        "the scenario should exercise the lease"
    );
    assert_eq!(text.matches(".deliver(").count(), deliveries.len());
    // Timer firings name the timer they fire.
    let fired_by_timer = trace["steps"]
        .as_array()
        .unwrap()
        .iter()
        .filter(|s| s["event"]["source"]["kind"] == json!("timer"))
        .count();
    assert_eq!(text.matches("Some(\"expiry\")").count(), fired_by_timer);
    assert!(fired_by_timer >= 1);

    for step in deliveries {
        let after = &step["config"]["machines"]["lease"];
        let vars = serde_json::to_string(&after["vars"]).unwrap();
        assert!(
            text.contains(&format!("json!({vars})")),
            "step {}: the variables {vars} are not in the test",
            step["index"]
        );
        for fired in step["fired"].as_array().unwrap() {
            let to = fired["to"].as_str().unwrap();
            assert!(text.contains(&format!("to: \"{to}\"")));
            for e in fired["emitted"].as_array().unwrap() {
                let value = json!({ "event": e["event"], "payload": e["payload"] });
                assert!(
                    text.contains(&serde_json::to_string(&value).unwrap()),
                    "the emitted event {value} is not in the test"
                );
            }
        }
    }
    // Receivers and deliveries come from the specification.
    // rustfmt may break a tuple across lines, so these compare with whitespace removed.
    let flat: String = text.chars().filter(|c| !c.is_whitespace()).collect();
    assert!(flat.contains("(\"worker\",\"at-least-once\","));
    assert!(flat.contains("(\"ledger\",\"at-least-once\","));
    assert!(flat.contains("(\"worker\",\"at-most-once\","));
    // A timer set carries its name and its delay in milliseconds.
    assert!(flat.contains("(\"expiry\",30,"));
}

/// The mutation check: the expected values are the trace's, so altering the trace's final state
/// alters exactly the expectation of the step that reaches it, and that expectation then no
/// longer equals what the generated lease computes, so the test body would fail.
#[test]
fn altering_the_traces_final_state_alters_exactly_that_expectation() {
    let trace = canned_trace();
    let before = generated(&spec_text(), &trace).unwrap();

    let mut altered = trace.clone();
    let last = altered["steps"]
        .as_array()
        .unwrap()
        .iter()
        .rposition(|s| {
            s["fired"]
                .as_array()
                .unwrap()
                .iter()
                .any(|f| f["behavior"] == json!("lease"))
        })
        .unwrap();
    let accepted = altered["steps"][last]["config"]["machines"]["lease"]["vars"]["accepted"]
        .as_u64()
        .unwrap();
    altered["steps"][last]["config"]["machines"]["lease"]["vars"]["accepted"] =
        json!(accepted + 100);
    let after = generated(&spec_text(), &altered).unwrap();

    assert_ne!(before, after);
    let wrong = format!("\"accepted\":{}", accepted + 100);
    assert!(after.contains(&wrong) && !before.contains(&wrong));
    let (b, a): (Vec<&str>, Vec<&str>) = (before.lines().collect(), after.lines().collect());
    assert_eq!(b.len(), a.len());
    let changed: Vec<(&&str, &&str)> = b.iter().zip(&a).filter(|(x, y)| x != y).collect();
    assert!(!changed.is_empty());
    for (x, y) in changed {
        assert!(
            y.contains(&wrong) && !x.contains(&wrong),
            "only the altered variables may change: {x} -> {y}"
        );
    }
}

