//! The capability catalogue: a golden fixture (`tests/fixtures/catalogue/expected`, rewritten by
//! `SPECC_BLESS=1`), what the fixture's catalogue holds and leaves out, the refusals, and the
//! catalogue of Strata's own specification, which stays within its size budget, lists every public
//! contract and is the committed `specifications/catalogue.md`.

use std::fs;
use std::path::PathBuf;

use strata_spec_compiler::catalogue;
use strata_spec_compiler::{jsonc, output, GeneratedFile};

const FIXTURE_SPEC: &str = "crates/spec-compiler/tests/fixtures/catalogue/spec.jsonc";

/// The budget of the catalogue of the real specification, in bytes.
const BUDGET_BYTES: usize = 150_000;

fn manifest_dir() -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR"))
}

fn repo_root() -> PathBuf {
    manifest_dir().join("../..")
}

fn fixture_text() -> String {
    fs::read_to_string(manifest_dir().join("tests/fixtures/catalogue/spec.jsonc")).unwrap()
}

fn fixture_files() -> Vec<GeneratedFile> {
    catalogue::generate(FIXTURE_SPEC, &fixture_text())
        .unwrap()
        .files
}

/// What follows the header of a generated catalogue. The committed file's header names the
/// semantic hash Exegra reports, which a test cannot compute, so only the rest is compared.
fn body(contents: &str) -> String {
    contents
        .replace('\r', "")
        .split_once("\n\n")
        .map(|(_, rest)| rest.to_string())
        .unwrap()
}

#[test]
fn golden_output_matches_the_expected_file() {
    let dir = manifest_dir().join("tests/fixtures/catalogue/expected");
    let files = fixture_files();
    if std::env::var("SPECC_BLESS").as_deref() == Ok("1") {
        output::write(&dir, &files).unwrap();
        return;
    }
    let differences = output::compare(&dir, &files).unwrap();
    assert!(
        differences.is_empty(),
        "tests/fixtures/catalogue/expected is not what specc catalogue generates: {differences:?}. \
         Run the test with SPECC_BLESS=1 to rewrite it, and review the change."
    );
}

#[test]
fn the_fixture_catalogue_lists_public_contracts_and_domain_events_only() {
    let files = fixture_files();
    assert_eq!(files, fixture_files());
    assert_eq!(files.len(), 1);
    assert_eq!(files[0].path, "catalogue.md");
    let text = &files[0].contents;
    assert!(text.starts_with(
        "# @generated by specc from crates/spec-compiler/tests/fixtures/catalogue/spec.jsonc."
    ));
    // Public contracts only, with the implementation status of their component.
    assert!(text.contains("\n- publish-post: Publish a post |"));
    assert!(text.contains("by worker (NOT IMPLEMENTED)"));
    assert!(text.contains("by gateway (manual)"));
    assert!(text.contains("by none"));
    assert!(!text.contains("sweep-posts"));
    assert!(text.contains("## Public contracts (3)"));
    // Domain events only.
    assert!(text.contains("\n- post-published: post:post-id, change:change"));
    assert!(text.contains("\n- post-archived: -"));
    assert!(!text.contains("sweep-due"));
    // Only the types the listed contracts and events name, through list<...> as well.
    for named in ["post-id", "tag", "post-state", "post", "change"] {
        assert!(
            text.contains(&format!("\n- {named}: ")),
            "type {named} is missing"
        );
    }
    assert!(!text.contains("unlisted"));
    // Roles by capability, in sorted order.
    assert!(text.contains("\n- post-read [core]: Read posts. | owner,reader"));
    assert!(text.contains("\n- post-publish: Make a post visible. | -"));
}

#[test]
fn a_specification_that_is_not_jsonc_or_not_an_object_is_refused() {
    let codes = |text: &str| -> Vec<String> {
        catalogue::generate(FIXTURE_SPEC, text)
            .unwrap_err()
            .into_iter()
            .map(|d| d.code)
            .collect()
    };
    assert_eq!(codes("{ not json"), [catalogue::SYNTAX]);
    assert_eq!(codes("[]"), [catalogue::SHAPE]);
}

#[test]
fn the_catalogue_of_the_real_specification_is_small_and_lists_every_public_contract() {
    let spec = "specifications/spec.jsonc";
    let text = fs::read_to_string(repo_root().join(spec)).unwrap();
    let files = catalogue::generate(spec, &text).unwrap().files;
    let generated = &files[0].contents;
    assert!(
        generated.len() <= BUDGET_BYTES,
        "the catalogue is {} bytes; the budget is {BUDGET_BYTES}",
        generated.len()
    );

    let value = jsonc::parse(&text).unwrap();
    let public: Vec<&str> = value["contracts"]
        .as_array()
        .unwrap()
        .iter()
        .filter(|c| c["exposure"] == "public")
        .map(|c| c["id"].as_str().unwrap())
        .collect();
    assert!(!public.is_empty());
    for id in &public {
        assert!(
            generated.contains(&format!("\n- {id}: ")),
            "public contract {id} is missing from the catalogue"
        );
    }
    assert!(generated.contains(&format!("## Public contracts ({})", public.len())));
}

#[test]
fn the_committed_catalogue_is_what_specc_catalogue_generates() {
    let committed = fs::read_to_string(repo_root().join("specifications/catalogue.md")).unwrap();
    let spec = "specifications/spec.jsonc";
    let text = fs::read_to_string(repo_root().join(spec)).unwrap();
    let generated = catalogue::generate(spec, &text)
        .unwrap()
        .files
        .remove(0)
        .contents;
    assert_eq!(
        body(&committed),
        body(&generated),
        "specifications/catalogue.md is stale; run npm run generate"
    );
}

#[test]
fn markdown_syntax_in_a_description_cannot_forge_a_column_or_a_link() {
    let text = serde_json::json!({
        "capabilities": [
            { "id": "cap-a", "description": "reads | auth anonymous [click](http://evil) <b>x</b> *y*" }
        ]
    })
    .to_string();
    let files = catalogue::generate("spec.jsonc", &text).unwrap().files;
    let line = files[0]
        .contents
        .lines()
        .find(|l| l.starts_with("- cap-a"))
        .unwrap();
    assert!(
        line.contains(r"reads \| auth anonymous \[click\](http://evil) \<b\>x\</b\> \*y\*"),
        "{line}"
    );
    // The only column separator is the one specc writes.
    assert_eq!(line.replace(r"\|", "").matches('|').count(), 1, "{line}");
}
