//! Crate assembly: the backends' modules, the prelude, `lib.rs` and `Cargo.toml`, formatted by
//! prettyplease and headed with the generated-file marker.

use proc_macro2::{Ident, Span, TokenStream};
use quote::quote;

use crate::backend::{prelude, BACKENDS};
use crate::diagnostic::Diagnostic;
use crate::ir::Spec;

/// The serde version the generated crate depends on (the workspace's).
pub const SERDE_VERSION: &str = "1.0.228";
/// The uuid version the generated crate depends on (the workspace's).
pub const UUID_VERSION: &str = "1.24.0";
/// The regex version the generated crate depends on (the workspace's).
pub const REGEX_VERSION: &str = "1.13.1";

/// Code of a module that does not parse as Rust: a defect in specc, never in the specification.
pub const INTERNAL: &str = "specc.internal";

/// The start of the first line of every file specc writes. Only files that start with one of
/// these are ever replaced or removed.
pub const HEADER_MARKERS: [&str; 2] = ["// @generated by specc", "# @generated by specc"];

/// One file of the generated crate.
#[derive(Debug, Clone, PartialEq, Eq, PartialOrd, Ord)]
pub struct GeneratedFile {
    /// The path relative to the crate directory, with forward slashes.
    pub path: String,
    /// The file's contents, with `\n` line endings.
    pub contents: String,
}

/// The header line of a generated Rust file.
pub fn rust_header(spec_path: &str) -> String {
    format!(
        "{} from {spec_path}. Do not edit; change the specification and regenerate.",
        HEADER_MARKERS[0]
    )
}

/// The header line of the generated `Cargo.toml`.
pub fn toml_header(spec_path: &str) -> String {
    format!(
        "{} from {spec_path}. Do not edit; change the specification and regenerate.",
        HEADER_MARKERS[1]
    )
}

/// Every file of the generated crate, sorted by path. Assumes the readiness checks passed.
pub fn crate_files(spec: &Spec, crate_name: &str) -> Result<Vec<GeneratedFile>, Vec<Diagnostic>> {
    let mut files = vec![GeneratedFile {
        path: "Cargo.toml".to_string(),
        contents: cargo_toml(spec, crate_name),
    }];
    let mut errors = Vec::new();
    let mut modules: Vec<(&str, TokenStream)> = vec![(prelude::MODULE, prelude::emit())];
    for backend in BACKENDS {
        modules.push((backend.module(), backend.emit(spec)));
    }
    let lib = lib_rs(spec, modules.iter().map(|(name, _)| *name));
    modules.push(("lib", lib));
    for (module, tokens) in modules {
        match rust_file(spec, tokens) {
            Ok(contents) => files.push(GeneratedFile {
                path: format!("src/{module}.rs"),
                contents,
            }),
            Err(e) => errors.push(Diagnostic::new(
                INTERNAL,
                module,
                format!("specc produced a module that is not valid Rust ({e}); this is a defect in specc."),
            )),
        }
    }
    if !errors.is_empty() {
        return Err(errors);
    }
    files.sort();
    Ok(files)
}

fn rust_file(spec: &Spec, tokens: TokenStream) -> Result<String, syn::Error> {
    let file: syn::File = syn::parse2(tokens)?;
    let body = separate_items(&prettyplease::unparse(&file));
    Ok(format!("{}\n{body}", rust_header(&spec.path)))
}

/// Puts one blank line before every item that prettyplease left directly after the previous one,
/// at any nesting depth, so the generated files read like hand-written ones. An item starts at its
/// first doc comment or attribute; lines inside an item's leading docs and attributes stay together.
fn separate_items(text: &str) -> String {
    let mut out = String::with_capacity(text.len() + text.len() / 16);
    let mut previous = "";
    for line in text.lines() {
        let trimmed = line.trim_start();
        let starts_item = trimmed.starts_with("///")
            || trimmed.starts_with("#[")
            || ITEM_KEYWORDS.iter().any(|k| trimmed.starts_with(k));
        let prev = previous.trim_start();
        let prev_continues = prev.is_empty()
            || prev.starts_with("///")
            || prev.starts_with("//!")
            || prev.starts_with("#[")
            || prev.starts_with("#![")
            || prev.ends_with('{')
            || prev.ends_with('(')
            || prev.ends_with(',');
        let same_indent = line.len() - trimmed.len() == previous.len() - prev.len();
        if starts_item && !prev_continues && same_indent {
            out.push('\n');
        }
        out.push_str(line);
        out.push('\n');
        previous = line;
    }
    out
}

const ITEM_KEYWORDS: &[&str] = &[
    "pub ", "impl ", "impl<", "fn ", "struct ", "enum ", "trait ", "const ", "static ", "type ",
    "mod ", "use ",
];

fn lib_rs<'a>(spec: &Spec, modules: impl Iterator<Item = &'a str>) -> TokenStream {
    let summary = format!(
        " {}: the declared types, records and contracts of its specification, as Rust.",
        spec.system.name
    );
    let origin = format!(
        " Generated by specc from system `{}`. Change the specification and regenerate; do not edit.",
        spec.system.id
    );
    let modules: Vec<Ident> = modules.map(|m| Ident::new(m, Span::call_site())).collect();
    quote! {
        #![doc = #summary]
        #![doc = ""]
        #![doc = #origin]
        #![warn(missing_docs)]
        #![allow(clippy::enum_variant_names)]

        #( pub mod #modules; )*
    }
}

fn cargo_toml(spec: &Spec, crate_name: &str) -> String {
    format!(
        "{header}\n\
         [package]\n\
         name = \"{crate_name}\"\n\
         version = \"0.1.0\"\n\
         edition = \"2021\"\n\
         publish = false\n\
         \n\
         [dependencies]\n\
         regex = \"{REGEX_VERSION}\"\n\
         serde = {{ version = \"{SERDE_VERSION}\", features = [\"derive\"] }}\n\
         uuid = {{ version = \"{UUID_VERSION}\", features = [\"serde\"] }}\n",
        header = toml_header(&spec.path),
    )
}

/// True when `name` can be the generated package's name: an ASCII letter followed by ASCII
/// letters, digits, `-` and `_`.
pub fn is_crate_name(name: &str) -> bool {
    let mut chars = name.chars();
    chars.next().is_some_and(|c| c.is_ascii_alphabetic())
        && chars.all(|c| c.is_ascii_alphanumeric() || c == '-' || c == '_')
}

#[cfg(test)]
mod tests {
    use super::*;

    /// The versions written into generated manifests are the workspace's.
    #[test]
    fn dependency_versions_match_the_workspace() {
        let root = concat!(env!("CARGO_MANIFEST_DIR"), "/../../Cargo.toml");
        let manifest = std::fs::read_to_string(root).unwrap();
        let line = |name: &str| {
            manifest
                .lines()
                .find(|l| l.starts_with(&format!("{name} = ")))
                .unwrap_or_else(|| panic!("no {name} in the workspace dependencies"))
                .to_string()
        };
        assert!(line("serde").contains(&format!("version = \"{SERDE_VERSION}\"")));
        assert!(line("uuid").contains(&format!("version = \"{UUID_VERSION}\"")));
        assert_eq!(line("regex"), format!("regex = \"{REGEX_VERSION}\""));
    }

    #[test]
    fn crate_names_are_checked() {
        assert!(is_crate_name("strata-spec"));
        assert!(is_crate_name("a_b2"));
        assert!(!is_crate_name(""));
        assert!(!is_crate_name("2a"));
        assert!(!is_crate_name("a b"));
        assert!(!is_crate_name("a\"b"));
    }

    #[test]
    fn headers_name_the_specification() {
        assert_eq!(
            rust_header("specs/a.jsonc"),
            "// @generated by specc from specs/a.jsonc. Do not edit; change the specification and regenerate."
        );
        assert!(toml_header("x").starts_with("# @generated by specc from x."));
    }
}
