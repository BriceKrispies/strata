// Fixture tests for scripts/generated-share.mjs. Run with: node --test scripts/generated-share.test.mjs
import assert from 'node:assert/strict';
import { mkdirSync, mkdtempSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join } from 'node:path';
import { after, test } from 'node:test';
import { rustLineShare } from './generated-share.mjs';

const made = [];

function fixture(files) {
  const dir = mkdtempSync(join(tmpdir(), 'generated-share-'));
  made.push(dir);
  for (const [rel, text] of Object.entries(files)) {
    const path = join(dir, rel);
    mkdirSync(dirname(path), { recursive: true });
    writeFileSync(path, text);
  }
  return dir;
}

after(() => {
  for (const dir of made) rmSync(dir, { recursive: true, force: true });
});

const nonBlank = (text) => text.split('\n').filter((line) => line.trim() !== '').length;

const HEADER = '// @generated by specc\n';

// The generated model crate: lib.rs, a large module `big` and a small module `other`.
const libRs = `${HEADER}pub mod big;\npub mod other;\n`;

const helperStruct = `pub struct Helper {\n    pub level: u8,\n}\n`;
const helperDefault = `impl Default for Helper {\n    fn default() -> Self {\n        Helper { level: 1 }\n    }\n}\n`;
const helperImpl = `impl Helper {\n    pub fn level(&self) -> u8 {\n        self.level\n    }\n}\n`;
const unrelatedRs = `pub struct Unrelated {\n    pub value: u32,\n}\n\nimpl Unrelated {\n    pub fn value(&self) -> u32 {\n        self.value\n    }\n}\n`;
const otherRs = `${HEADER}${helperStruct}\n${helperDefault}\n${helperImpl}\n${unrelatedRs}`;

const useLine = 'use crate::other::Helper;\n';
const targetStruct = `/// The target of the backend.
#[derive(Debug, Clone)]
pub struct Target {
    pub name: String,
    pub helper: Helper,
}
`;
const targetImpl = `impl Target {
    pub fn new(name: &str) -> Self {
        // A brace } in a comment must not close the impl.
        let open = "{";
        let close = '}';
        Self { name: format!("{open}{name}{close}"), helper: Helper::default() }
    }
}
`;
const displayImpl = `impl std::fmt::Display for Target {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        write!(f, "{}", self.name)
    }
}
`;
const unusedRs = `pub struct Unused {
    pub x: u32,
}

impl Unused {
    pub fn go(&self) -> u32 {
        self.x
    }
}
`;
const filler = Array.from({ length: 300 }, (_, i) => `pub fn filler_${i}() -> u32 {\n    ${i}\n}\n`).join('\n');
const bigRs = `${HEADER}${useLine}\n${targetStruct}\n${targetImpl}\n${displayImpl}\n${unusedRs}\n${filler}`;

const backendRs = `// Hand-written code of the shipped backend.
pub fn make() -> strata_model::big::Target {
    // strata_model::big::Unused is only mentioned in a comment.
    let label = "strata_model::big::Unused";
    let _ = label;
    strata_model::big::Target::new("make")
}
`;

test('a shipped file naming one type of a large module counts that type and what it uses', () => {
  const root = fixture({
    'crates/backend/Cargo.toml': '[package]\nname = "strata-backend"\n\n[dependencies]\nstrata-model = { path = "../model" }\n',
    'crates/backend/src/lib.rs': backendRs,
    'crates/model/Cargo.toml': '[package]\nname = "strata-model"\n',
    'crates/model/src/lib.rs': libRs,
    'crates/model/src/big.rs': bigRs,
    'crates/model/src/other.rs': otherRs,
  });

  const share = rustLineShare(root);

  // Target, the use of Helper it needs, and Helper's own items; the Unused type and the filler
  // functions are not named, so they do not count. `pub mod other;` counts because big.rs uses it.
  const expected =
    nonBlank(HEADER + useLine) +
    nonBlank(targetStruct) +
    nonBlank(targetImpl) +
    nonBlank(displayImpl) +
    nonBlank(HEADER + helperStruct) +
    nonBlank(helperDefault) +
    nonBlank(helperImpl) +
    nonBlank('pub mod other;\n');

  assert.equal(share.generated, expected);
  assert.equal(share.total, share.generated + share.handWritten);
  assert.deepEqual(share.generatedModules, ['strata_model::big', 'strata_model::other']);
  assert.equal(share.generatedFiles, 3);

  const byModule = Object.fromEntries(share.generatedItems.map((m) => [m.module, m]));
  assert.deepEqual(byModule['strata_model::big'].labels, ['impl Display for Target', 'impl Target', 'struct Target', 'use Helper']);
  assert.deepEqual(byModule['strata_model::other'].labels, ['impl Default for Helper', 'impl Helper', 'struct Helper']);
  assert.deepEqual(byModule.strata_model.labels, ['mod other']);
  assert.equal(JSON.stringify(share.generatedItems).includes('Unused'), false);
});

test('a shipped crate that names nothing from a generated crate counts no generated lines', () => {
  const root = fixture({
    'crates/backend/Cargo.toml': '[package]\nname = "strata-backend"\n\n[dependencies]\nstrata-model = { path = "../model" }\n',
    'crates/backend/src/lib.rs': 'pub fn nothing() -> u32 {\n    1\n}\n',
    'crates/model/Cargo.toml': '[package]\nname = "strata-model"\n',
    'crates/model/src/lib.rs': libRs,
    'crates/model/src/big.rs': bigRs,
    'crates/model/src/other.rs': otherRs,
  });

  const share = rustLineShare(root);

  assert.equal(share.generated, 0);
  assert.deepEqual(share.generatedModules, []);
  assert.deepEqual(share.generatedItems, []);
});
