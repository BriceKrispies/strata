// Measures of how much of the platform is generated from the specification. Used by
// scripts/spec-gate.mjs. Informational only: nothing here fails the gate.
//
// A Rust file is generated when its first line starts with GENERATED_HEADER.
//
// The generated share counts only code that is linked into a shipped binary. Generated code that
// only its own tests, a fixture or the Lean comparison run is not part of the platform, so it is
// not counted at all, on either side of the ratio. The rule, kept simple on purpose:
//
// 1. Shipped crates. Start from the crates of the shipped binaries (SHIPPED_CRATES) and follow
//    their [dependencies] (and target-specific dependencies) to other crates of this repository,
//    by `path`, directly or through [workspace.dependencies]. Dev- and build-dependencies are not
//    followed: they are not linked into the binary.
// 2. Lines. Non-blank lines of the .rs files under src/ of the shipped crates. tests/, benches/
//    and examples/ are not linked and are left out; #[cfg(test)] modules inside src/ are counted
//    as they stand, generated or not.
// 3. Generated crates, item by item. A crate whose lib.rs is generated (crates/model) is counted
//    per item of its top-level generated files src/<module>.rs, not per module. Each file is split
//    into top-level items (fn, struct, enum, union, trait, type, mod, const, static, macro_rules,
//    impl, use, extern, and anything else as "other"), each with its doc comments and attributes.
//    An item is counted when it is in the closure of the roots:
//    - Roots. Hand-written code of the shipped crates names generated items through paths
//      `<crate>::m::Item`, `<crate>::Item` and use trees such as `use <crate>::m::{A, B::C as D}`.
//      A path resolves to the item it names in module m, or to an item of that name anywhere in
//      the crate (re-exports). A path that ends at a module (`<crate>::m`, `<crate>::m::*`) counts
//      the whole module. A path that cannot be resolved, a bare `<crate>` (`use <crate>;`), or a
//      `<crate>` name used with no path, counts the whole crate.
//    - Closure. The identifiers of a counted item (code only: comments and string literals are
//      skipped) name the items it may use. Every item with such a name is counted, and so is
//      every impl block whose type or trait has that name. So an impl of a counted trait counts
//      whichever type it is for, and an impl counts with its type.
//    - Always counted: `use` items with a glob, `use ... as _`, `extern` items, `const _`, and
//      any top-level text the splitter does not recognise (macro invocations included). They are
//      compiled whether used or not, so they are not left out.
//    - Never counted: items under #[cfg(test)]. They are not linked.
//    Approximations, all on the side of over-counting:
//    - Names are matched, not resolved. Two items with the same name in different modules both
//      count when one of them is used.
//    - An impl block counts whole, so every method of a counted type comes with it.
//    - Items made by macros in the generated code are not seen. A root that names one is not
//      resolved, so it counts the whole crate.
//    - A generated file in a nested directory of a generated crate counts whole.
//    - The generated header line counts with the first item of its file.
//    The report lists, per module, the counted items and their lines (generatedItems).
// 4. A generated file inside a hand-written crate counts whole whenever that crate is shipped.
import { existsSync, readdirSync, readFileSync, statSync } from 'node:fs';
import { basename, dirname, join, resolve } from 'node:path';

export const GENERATED_HEADER = '// @generated by specc';

// The crates whose binaries are shipped: strata-backend and strata-bff.
export const SHIPPED_CRATES = ['crates/backend', 'crates/bff'];

export function isGenerated(text) {
  const first = text.split('\n', 1)[0].replace(/^﻿/, '').replace(/\r$/, '');
  return first.startsWith(GENERATED_HEADER);
}

function nonBlank(text) {
  return text.split('\n').filter((line) => line.trim() !== '').length;
}

// The repository crates a manifest links: `{name -> crate directory}` of its [dependencies] (and
// [target.*.dependencies]) that have a path, given directly or through [workspace.dependencies].
function linkedCrates(crateDir, workspacePaths) {
  const manifest = join(crateDir, 'Cargo.toml');
  if (!existsSync(manifest)) return [];
  const found = [];
  let linked = false;
  for (const raw of readFileSync(manifest, 'utf8').split(/\r?\n/)) {
    const line = raw.replace(/#.*$/, '').trim();
    const section = line.match(/^\[(.+)\]$/);
    if (section) {
      linked = section[1] === 'dependencies' || /^target\..+\.dependencies$/.test(section[1]);
      continue;
    }
    if (!linked) continue;
    const entry = line.match(/^([A-Za-z0-9_-]+)(\.workspace)?\s*=\s*(.*)$/);
    if (!entry) continue;
    const [, name, dotted, value] = entry;
    const path = value.match(/path\s*=\s*"([^"]+)"/);
    if (path) found.push(resolve(crateDir, path[1]));
    else if ((dotted || /workspace\s*=\s*true/.test(value)) && workspacePaths.has(name)) found.push(workspacePaths.get(name));
  }
  return found;
}

// `{name -> crate directory}` of the root manifest's [workspace.dependencies] that have a path.
function workspaceDependencyPaths(root) {
  const paths = new Map();
  const manifest = join(root, 'Cargo.toml');
  if (!existsSync(manifest)) return paths;
  let inSection = false;
  for (const raw of readFileSync(manifest, 'utf8').split(/\r?\n/)) {
    const line = raw.replace(/#.*$/, '').trim();
    const section = line.match(/^\[(.+)\]$/);
    if (section) {
      inSection = section[1] === 'workspace.dependencies';
      continue;
    }
    const entry = inSection && line.match(/^([A-Za-z0-9_-]+)\s*=\s*\{.*path\s*=\s*"([^"]+)"/);
    if (entry) paths.set(entry[1], resolve(root, entry[2]));
  }
  return paths;
}

function packageName(crateDir) {
  const manifest = join(crateDir, 'Cargo.toml');
  const name = existsSync(manifest) && readFileSync(manifest, 'utf8').match(/^\s*name\s*=\s*"([^"]+)"/m);
  return name ? name[1] : '';
}

function rustFiles(dir) {
  const files = [];
  const walk = (current) => {
    for (const entry of readdirSync(current)) {
      const path = join(current, entry);
      if (statSync(path).isDirectory()) {
        if (entry !== 'target') walk(path);
      } else if (entry.endsWith('.rs')) {
        files.push(path);
      }
    }
  };
  if (existsSync(dir)) walk(dir);
  return files;
}

// ---- Lexing -------------------------------------------------------------------------------------
//
// A small Rust lexer. It knows line and nested block comments, string, raw string and byte string
// literals, char literals and lifetimes, so that braces, semicolons and names inside them are not
// read as code. It is not a parser: it only has to find top-level item boundaries and names.

const WS = /\s+/uy;
const IDENT = /r#[\p{L}_][\p{L}\p{N}_]*|[\p{L}_][\p{L}\p{N}_]*/uy;
const NUMBER = /\d[\p{L}\p{N}_.]*/uy;

function matchAt(re, text, at) {
  re.lastIndex = at;
  const m = re.exec(text);
  return m ? m[0] : null;
}

// Tokens `{type, start, end, text}` with type one of ws, comment, str, char, life, ident, num, punct.
function tokenize(text) {
  const tokens = [];
  const n = text.length;
  let i = 0;
  const add = (type, end) => {
    tokens.push({ type, start: i, end, text: text.slice(i, end) });
    i = end;
  };
  while (i < n) {
    const c = text[i];
    const next = text[i + 1];
    const ws = matchAt(WS, text, i);
    if (ws) {
      add('ws', i + ws.length);
      continue;
    }
    if (c === '/' && next === '/') {
      const nl = text.indexOf('\n', i);
      add('comment', nl < 0 ? n : nl);
      continue;
    }
    if (c === '/' && next === '*') {
      let depth = 0;
      let j = i;
      while (j < n) {
        if (text.startsWith('/*', j)) {
          depth += 1;
          j += 2;
        } else if (text.startsWith('*/', j)) {
          depth -= 1;
          j += 2;
          if (depth === 0) break;
        } else {
          j += 1;
        }
      }
      add('comment', j);
      continue;
    }
    const raw = text.slice(i, i + 40).match(/^(?:b|c)?r(#*)"/);
    if (raw) {
      const close = `"${raw[1]}`;
      const at = text.indexOf(close, i + raw[0].length);
      add('str', at < 0 ? n : at + close.length);
      continue;
    }
    if (c === '"' || ((c === 'b' || c === 'c') && next === '"')) {
      let j = c === '"' ? i + 1 : i + 2;
      while (j < n && text[j] !== '"') j += text[j] === '\\' ? 2 : 1;
      add('str', Math.min(j + 1, n));
      continue;
    }
    if (c === "'") {
      if (next === '\\') {
        const close = text.indexOf("'", i + 3);
        add('char', close < 0 ? n : close + 1);
        continue;
      }
      const cp = text.codePointAt(i + 1);
      if (cp !== undefined) {
        const len = cp > 0xffff ? 2 : 1;
        if (text[i + 1 + len] === "'") {
          add('char', i + 2 + len);
          continue;
        }
      }
      const life = matchAt(IDENT, text, i + 1);
      add('life', i + 1 + (life ? life.length : 0));
      continue;
    }
    const id = matchAt(IDENT, text, i);
    if (id) {
      add('ident', i + id.length);
      continue;
    }
    const num = matchAt(NUMBER, text, i);
    if (num) {
      add('num', i + num.length);
      continue;
    }
    if (c === ':' && next === ':') {
      add('punct', i + 2);
      continue;
    }
    add('punct', i + 1);
  }
  return tokens;
}

const isSig = (t) => t.type !== 'ws' && t.type !== 'comment';
const sigTokens = (text) => tokenize(text).filter(isSig);

function nextSig(tokens, k) {
  let j = k;
  while (j < tokens.length && !isSig(tokens[j])) j += 1;
  return j;
}

// Index of the bracket closing the one at `open` (any of () [] {}), or the last token.
function matchClose(tokens, open) {
  let depth = 0;
  for (let k = open; k < tokens.length; k += 1) {
    const t = tokens[k];
    if (t.type !== 'punct') continue;
    if (t.text === '(' || t.text === '[' || t.text === '{') depth += 1;
    else if (t.text === ')' || t.text === ']' || t.text === '}') {
      depth -= 1;
      if (depth === 0) return k;
    }
  }
  return tokens.length - 1;
}

// ---- Use trees and paths ------------------------------------------------------------------------
//
// Parses a use tree or a path from significant tokens. `prefix` is the path before `start`. Each
// leaf is pushed as {path, alias, glob}; `self` at the end of a leaf is dropped. A tree ends at
// the first token that cannot continue it (`,`, `}`, `;`, `(`, `<`, `{` after an item name, ...).

function parseTree(toks, start, prefix, out) {
  let i = start;
  const path = [...prefix];
  for (;;) {
    const t = toks[i];
    if (t && t.type === 'ident') {
      path.push(t.text);
      i += 1;
      if (toks[i] && toks[i].text === '::') {
        i += 1;
        continue;
      }
      let alias = null;
      if (toks[i] && toks[i].type === 'ident' && toks[i].text === 'as') {
        alias = toks[i + 1] ? toks[i + 1].text : null;
        i += 2;
      }
      const leaf = path[path.length - 1] === 'self' ? path.slice(0, -1) : path;
      out.push({ path: leaf, alias, glob: false });
      return i;
    }
    if (t && t.text === '::') {
      i += 1;
      continue;
    }
    if (t && t.text === '*') {
      out.push({ path, alias: null, glob: true });
      return i + 1;
    }
    if (t && t.text === '{') {
      i += 1;
      while (i < toks.length && toks[i].text !== '}') {
        const before = i;
        i = parseTree(toks, i, path, out);
        if (toks[i] && toks[i].text === ',') i += 1;
        else if (i === before) i += 1;
      }
      return i + 1;
    }
    if (path.length > prefix.length) out.push({ path, alias: null, glob: false });
    return i;
  }
}

// The crate paths of a file's code: each leaf after `<ident>::`, and whether the crate is named
// on its own (`use <ident>;`, `extern crate <ident> as x;`), which counts the whole crate.
function crateRoots(sigs, ident) {
  const leaves = [];
  let whole = false;
  sigs.forEach((t, k) => {
    if (t.type !== 'ident' || t.text !== ident) return;
    if (sigs[k + 1] && sigs[k + 1].text === '::') parseTree(sigs, k + 2, [], leaves);
    else whole = true;
  });
  return { leaves, whole };
}

// ---- Items --------------------------------------------------------------------------------------

const OPEN = new Set(['(', '[', '{']);
const CLOSE = new Set([')', ']', '}']);
// Items that end at a `;` only: their braces are values (`const X: T = if a { 1 } else { 2 };`).
const SEMICOLON_ITEMS = new Set(['const', 'static', 'type', 'use']);
const HEAD = /^(?:pub(?:\s*\([^)]*\))?\s+)?(?:(?:unsafe|async|default|extern(?:\s+"[^"]*")?|const)\s+)*(fn|struct|enum|union|trait|impl|mod|type|const|static|use|macro_rules|extern)\b/;
const CFG_TEST = /#\s*\[\s*cfg\s*\(\s*test\s*\)\s*\]/;

// The name a declaration introduces: the first identifier after its keyword (`mut` skipped).
function declaredName(sigs, kind) {
  const kw = sigs.findIndex((t) => t.type === 'ident' && t.text === kind);
  for (let k = kw + 1; k < sigs.length; k += 1) {
    const t = sigs[k];
    if (t.type === 'ident' && t.text !== 'mut') return t.text;
    if (t.type === 'punct' && t.text === '!') continue;
    break;
  }
  return null;
}

// The last name of a type or trait path, `null` when the part is not a path (a slice, a tuple).
function headName(parts) {
  let name = null;
  for (let m = 0; m < parts.length; m += 1) {
    const t = parts[m];
    if (t.type === 'ident') {
      if (t.text === 'dyn' || t.text === 'mut' || t.text === 'impl') continue;
      name = t.text;
      if (parts[m + 1] && parts[m + 1].text === '::') continue;
      return name;
    }
    if (t.type === 'life' || (t.type === 'punct' && (t.text === '&' || t.text === '::'))) continue;
    return null;
  }
  return name;
}

// `impl<..> Trait for Type<..> where ..` gives {traitName, typeName}; an inherent `impl Type` has
// no trait.
function implHeader(sigs) {
  let k = sigs.findIndex((t) => t.type === 'ident' && t.text === 'impl') + 1;
  if (sigs[k] && sigs[k].text === '<') {
    let depth = 0;
    for (; k < sigs.length; k += 1) {
      if (sigs[k].text === '<') depth += 1;
      else if (sigs[k].text === '>') {
        depth -= 1;
        if (depth === 0) {
          k += 1;
          break;
        }
      }
    }
  }
  const parts = [[]];
  let angle = 0;
  let paren = 0;
  for (; k < sigs.length; k += 1) {
    const t = sigs[k];
    if (t.text === '{') break;
    if (t.type === 'ident' && t.text === 'where' && angle === 0 && paren === 0) break;
    if (t.text === '<') angle += 1;
    else if (t.text === '>') angle -= 1;
    else if (t.text === '(') paren += 1;
    else if (t.text === ')') paren -= 1;
    if (t.type === 'ident' && t.text === 'for' && angle === 0 && paren === 0) {
      parts.push([]);
      continue;
    }
    parts[parts.length - 1].push(t);
  }
  if (parts.length === 1) return { traitName: null, typeName: headName(parts[0]) };
  return { traitName: headName(parts[0]), typeName: headName(parts[1]) };
}

// One top-level chunk of a file: its text (prefix included), the names it declares, and what it
// uses. `always` items are counted whatever is used.
function describeItem(kind, chunkText, prefixText, toks) {
  const sigs = toks.filter(isSig);
  const headAt = sigs.findIndex((t) => t.type === 'ident' && t.text === kind);
  const head = sigs.slice(Math.max(0, headAt));
  const item = {
    kind,
    names: [],
    typeName: null,
    traitName: null,
    always: false,
    cfgTest: CFG_TEST.test(prefixText),
    text: chunkText,
    idents: new Set(sigs.filter((t) => t.type === 'ident').map((t) => t.text)),
    lines: nonBlank(chunkText),
    label: kind,
  };
  switch (kind) {
    case 'fn':
    case 'struct':
    case 'enum':
    case 'union':
    case 'trait':
    case 'type':
    case 'mod':
    case 'const':
    case 'static':
    case 'macro_rules': {
      const name = declaredName(head, kind);
      if (name && name !== '_') {
        item.names.push(name);
        item.label = `${kind} ${name}`;
      } else {
        item.always = true;
      }
      break;
    }
    case 'impl': {
      const header = implHeader(head);
      item.typeName = header.typeName;
      item.traitName = header.traitName;
      item.label = `impl${header.traitName ? ` ${header.traitName} for` : ''} ${header.typeName ?? '?'}`;
      break;
    }
    case 'use': {
      const leaves = [];
      parseTree(head, head.findIndex((t) => t.text === 'use') + 1, [], leaves);
      for (const leaf of leaves) {
        if (leaf.glob || leaf.alias === '_' || leaf.path.length === 0) {
          item.always = true;
        } else {
          item.names.push(leaf.alias ?? leaf.path[leaf.path.length - 1]);
        }
      }
      item.label = `use ${item.names.join(', ') || '*'}`;
      break;
    }
    default:
      item.always = true;
  }
  return item;
}

// Splits a Rust file into its top-level items, in order. Each chunk runs from the end of the
// previous item to the end of its own item, so its leading comments and attributes come with it.
function splitItems(text) {
  const tokens = tokenize(text);
  const n = tokens.length;
  const items = [];
  let chunk = 0;
  let charStart = 0;
  for (;;) {
    let j = chunk;
    while (j < n) {
      const t = tokens[j];
      if (!isSig(t)) {
        j += 1;
        continue;
      }
      if (t.type === 'punct' && t.text === '#') {
        let a = nextSig(tokens, j + 1);
        if (a < n && tokens[a].text === '!') a = nextSig(tokens, a + 1);
        if (a < n && tokens[a].text === '[') {
          j = matchClose(tokens, a) + 1;
          continue;
        }
      }
      break;
    }
    if (j >= n) {
      const rest = text.slice(charStart);
      if (rest.trim() !== '') items.push(describeItem('other', rest, rest, tokens.slice(chunk)));
      break;
    }

    const headText = text.slice(tokens[j].start, tokens[j].start + 400);
    const match = headText.match(HEAD);
    const kind = match ? match[1] : 'other';
    const semicolonOnly = SEMICOLON_ITEMS.has(kind);
    let depth = 0;
    const stack = [];
    let end = n - 1;
    for (let k = j; k < n; k += 1) {
      const t = tokens[k];
      if (t.type !== 'punct') continue;
      if (OPEN.has(t.text)) {
        depth += 1;
        stack.push(t.text);
      } else if (CLOSE.has(t.text)) {
        const opener = stack.pop();
        depth = Math.max(0, depth - 1);
        if (depth === 0 && t.text === '}' && opener === '{' && !semicolonOnly) {
          end = k;
          const after = nextSig(tokens, k + 1);
          if (after < n && tokens[after].text === ';') end = after;
          break;
        }
      } else if (t.text === ';' && depth === 0) {
        end = k;
        break;
      }
    }

    const stop = tokens[end].end;
    items.push(describeItem(kind, text.slice(charStart, stop), text.slice(charStart, tokens[j].start), tokens.slice(chunk, end + 1)));
    charStart = stop;
    chunk = end + 1;
  }
  return items;
}

// ---- Generated crates ---------------------------------------------------------------------------

// Counts the items of a generated crate's top-level generated modules that the hand-written
// code links, per the closure rule in the header. `handSigs` are the significant tokens of the
// hand-written shipped files.
function countGeneratedCrate(src, ident, handSigs) {
  const modules = new Map();
  for (const path of rustFiles(src)) {
    if (resolve(dirname(path)) !== resolve(src)) continue;
    const text = readFileSync(path, 'utf8');
    if (!isGenerated(text)) continue;
    modules.set(basename(path, '.rs'), splitItems(text));
  }

  const all = [];
  for (const [module, items] of modules) {
    for (const item of items) {
      if (item.cfgTest) continue;
      item.module = module;
      all.push(item);
    }
  }

  const byName = new Map();
  const byAttach = new Map();
  const index = (map, key, item) => {
    if (!map.has(key)) map.set(key, []);
    map.get(key).push(item);
  };
  for (const item of all) {
    for (const name of item.names) index(byName, name, item);
    if (item.typeName) index(byAttach, item.typeName, item);
    if (item.traitName) index(byAttach, item.traitName, item);
  }

  const counted = new Set();
  const queue = [];
  const referenced = new Set();
  const count = (item) => {
    if (counted.has(item)) return;
    counted.add(item);
    queue.push(item);
  };
  const reference = (name) => {
    if (referenced.has(name)) return;
    referenced.add(name);
    for (const item of byName.get(name) ?? []) count(item);
    for (const item of byAttach.get(name) ?? []) count(item);
  };
  const countModule = (module) => all.filter((item) => item.module === module).forEach(count);
  const countAll = () => all.forEach(count);

  all.filter((item) => item.always).forEach(count);

  const roots = [];
  let whole = false;
  for (const sigs of handSigs) {
    const found = crateRoots(sigs, ident);
    roots.push(...found.leaves);
    if (found.whole) whole = true;
  }
  if (whole) countAll();
  for (const { path: segs } of roots) {
    const [head, ...rest] = segs;
    if (head === undefined || head === 'self' || head === 'super' || head === 'crate') {
      countAll();
      continue;
    }
    if (modules.has(head) && head !== 'lib') {
      if (rest.length === 0) {
        countModule(head);
        continue;
      }
      const inModule = all.filter((item) => item.module === head && item.names.includes(rest[0]));
      const found = inModule.length ? inModule : all.filter((item) => item.names.includes(rest[0]));
      if (found.length) found.forEach(count);
      else countModule(head);
      continue;
    }
    const found = all.filter((item) => item.names.includes(head));
    if (found.length) found.forEach(count);
    else countAll();
  }

  while (queue.length) {
    const item = queue.pop();
    for (const name of item.names) reference(name);
    for (const id of item.idents) reference(id);
  }

  const result = { lines: 0, modules: [] };
  for (const module of [...modules.keys()].sort()) {
    const mine = all.filter((item) => item.module === module && counted.has(item));
    if (mine.length === 0) continue;
    const lines = mine.reduce((sum, item) => sum + item.lines, 0);
    result.lines += lines;
    result.modules.push({ module, items: mine.length, lines, labels: mine.map((item) => item.label).sort() });
  }
  return result;
}

// Non-blank lines of the Rust code linked into the shipped binaries, split by whether it is
// generated. See the header for the rule.
export function rustLineShare(root) {
  const share = {
    generated: 0,
    handWritten: 0,
    total: 0,
    generatedFiles: 0,
    files: 0,
    crates: [],
    generatedModules: [],
    generatedItems: [],
  };
  const workspacePaths = workspaceDependencyPaths(root);
  const shipped = new Set();
  const queue = SHIPPED_CRATES.map((dir) => resolve(root, dir)).filter((dir) => existsSync(dir));
  while (queue.length) {
    const dir = queue.shift();
    if (shipped.has(dir)) continue;
    shipped.add(dir);
    queue.push(...linkedCrates(dir, workspacePaths));
  }

  const handTexts = [];
  const generatedCrates = [];
  for (const dir of shipped) {
    const src = join(dir, 'src');
    const lib = join(src, 'lib.rs');
    const wholeCrateGenerated = existsSync(lib) && isGenerated(readFileSync(lib, 'utf8'));
    share.crates.push(packageName(dir));
    if (wholeCrateGenerated) generatedCrates.push({ src, ident: packageName(dir).replace(/-/g, '_') });
    for (const path of rustFiles(src)) {
      const text = readFileSync(path, 'utf8');
      // The top-level generated files of a generated crate are counted item by item below.
      if (wholeCrateGenerated && resolve(dirname(path)) === resolve(src) && isGenerated(text)) continue;
      share.files += 1;
      if (isGenerated(text)) {
        share.generated += nonBlank(text);
        share.generatedFiles += 1;
      } else {
        share.handWritten += nonBlank(text);
        handTexts.push(text);
      }
    }
  }

  const handSigs = handTexts.map(sigTokens);
  for (const { src, ident } of generatedCrates) {
    const crate = countGeneratedCrate(src, ident, handSigs);
    share.generated += crate.lines;
    share.generatedFiles += crate.modules.length;
    share.files += crate.modules.length;
    for (const m of crate.modules) {
      const module = m.module === 'lib' ? ident : `${ident}::${m.module}`;
      if (m.module !== 'lib') share.generatedModules.push(module);
      share.generatedItems.push({ module, items: m.items, lines: m.lines, labels: m.labels });
    }
  }

  share.generatedModules.sort();
  share.generatedItems.sort((a, b) => a.module.localeCompare(b.module));
  share.crates.sort();
  share.total = share.generated + share.handWritten;
  return share;
}

// Generated tests passing, from cargo test output (stdout followed by stderr, as the gate records it).
//
// Each test binary prints "Running <root source file>" (or "Doc-tests <crate>") on stderr, in the same
// order as its "running N tests" block on stdout. The k-th block is paired with the k-th Running line.
// A test is mapped to the file its module path names: for a binary whose root is in a src directory,
// the deepest existing module file (src/a/b.rs or src/a/b/mod.rs for the path a::b::name), else the
// root file itself (lib.rs, main.rs, or tests/x.rs for an integration test). A test is generated when
// that file is generated. Tests of doc-tests and unpaired binaries are reported as unmapped.
export function generatedTests(root, cargoText) {
  const result = { total: 0, passed: 0, unmapped: 0 };
  const lines = cargoText.split(/\r?\n/);

  const runs = [];
  const blocks = [];
  let current = null;
  for (const line of lines) {
    const run = line.match(/^\s*(Running|Doc-tests)\s+(?:unittests\s+)?(.+?)\s*(?:\([^()]*\))?\s*$/);
    if (run) {
      runs.push(run[1] === 'Running' ? run[2].replace(/\\/g, '/') : null);
      continue;
    }
    if (/^running \d+ tests?\s*$/.test(line)) {
      current = [];
      blocks.push(current);
      continue;
    }
    const test = line.match(/^test (\S+) \.\.\. (ok|FAILED)\s*$/);
    if (test && current) current.push({ name: test[1], passed: test[2] === 'ok' });
  }

  const all = blocks.reduce((sum, block) => sum + block.length, 0);
  if (runs.length !== blocks.length) {
    result.unmapped = all;
    return result;
  }

  const generatedOf = new Map();
  const isGeneratedFile = (file) => {
    if (!generatedOf.has(file)) generatedOf.set(file, isGenerated(readFileSync(join(root, file), 'utf8')));
    return generatedOf.get(file);
  };

  blocks.forEach((block, index) => {
    const rootFile = runs[index];
    if (!rootFile || !existsSync(join(root, rootFile))) {
      result.unmapped += block.length;
      return;
    }
    for (const test of block) {
      const file = testFile(root, rootFile, test.name);
      if (!isGeneratedFile(file)) continue;
      result.total += 1;
      if (test.passed) result.passed += 1;
    }
  });
  return result;
}

function testFile(root, rootFile, name) {
  const base = dirname(rootFile);
  if (!/(^|\/)src$/.test(base)) return rootFile;
  const modules = name.split('::').slice(0, -1);
  for (let k = modules.length; k >= 1; k -= 1) {
    const stem = [base, ...modules.slice(0, k)].join('/');
    if (existsSync(join(root, `${stem}.rs`))) return `${stem}.rs`;
    if (existsSync(join(root, `${stem}/mod.rs`))) return `${stem}/mod.rs`;
  }
  return rootFile;
}
