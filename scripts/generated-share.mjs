// Measures of how much of the platform is generated from the specification. Used by
// scripts/spec-gate.mjs. Informational only: nothing here fails the gate.
//
// A Rust file is generated when its first line starts with GENERATED_HEADER.
//
// The generated share counts only code that is linked into a shipped binary. Generated code that
// only its own tests, a fixture or the Lean comparison run is not part of the platform, so it is
// not counted at all, on either side of the ratio. The rule, kept simple on purpose:
//
// 1. Shipped crates. Start from the crates of the shipped binaries (SHIPPED_CRATES) and follow
//    their [dependencies] (and target-specific dependencies) to other crates of this repository,
//    by `path`, directly or through [workspace.dependencies]. Dev- and build-dependencies are not
//    followed: they are not linked into the binary.
// 2. Lines. Non-blank lines of the .rs files under src/ of the shipped crates. tests/, benches/
//    and examples/ are not linked and are left out; #[cfg(test)] modules inside src/ are counted
//    as they stand, generated or not.
// 3. Generated modules. A crate whose lib.rs is generated (crates/model) counts only its
//    referenced modules: a top-level module `m` is referenced when a hand-written file of a
//    shipped crate names `<crate>::m` (also inside `<crate>::{..}`), or when a referenced module
//    names `crate::m`. Its lib.rs counts once any module does. A crate that merely depends on it
//    without naming a module adds nothing. Module granularity is coarse: naming one type of
//    `contracts` counts the whole module, so the report lists the modules counted.
// 4. A generated file inside a hand-written crate counts whenever that crate is shipped.
import { existsSync, readdirSync, readFileSync, statSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';

export const GENERATED_HEADER = '// @generated by specc';

// The crates whose binaries are shipped: strata-backend and strata-bff.
export const SHIPPED_CRATES = ['crates/backend', 'crates/bff'];

export function isGenerated(text) {
  const first = text.split('\n', 1)[0].replace(/^﻿/, '').replace(/\r$/, '');
  return first.startsWith(GENERATED_HEADER);
}

function nonBlank(text) {
  return text.split('\n').filter((line) => line.trim() !== '').length;
}

// The repository crates a manifest links: `{name -> crate directory}` of its [dependencies] (and
// [target.*.dependencies]) that have a path, given directly or through [workspace.dependencies].
function linkedCrates(crateDir, workspacePaths) {
  const manifest = join(crateDir, 'Cargo.toml');
  if (!existsSync(manifest)) return [];
  const found = [];
  let linked = false;
  for (const raw of readFileSync(manifest, 'utf8').split(/\r?\n/)) {
    const line = raw.replace(/#.*$/, '').trim();
    const section = line.match(/^\[(.+)\]$/);
    if (section) {
      linked = section[1] === 'dependencies' || /^target\..+\.dependencies$/.test(section[1]);
      continue;
    }
    if (!linked) continue;
    const entry = line.match(/^([A-Za-z0-9_-]+)(\.workspace)?\s*=\s*(.*)$/);
    if (!entry) continue;
    const [, name, dotted, value] = entry;
    const path = value.match(/path\s*=\s*"([^"]+)"/);
    if (path) found.push(resolve(crateDir, path[1]));
    else if ((dotted || /workspace\s*=\s*true/.test(value)) && workspacePaths.has(name)) found.push(workspacePaths.get(name));
  }
  return found;
}

// `{name -> crate directory}` of the root manifest's [workspace.dependencies] that have a path.
function workspaceDependencyPaths(root) {
  const paths = new Map();
  const manifest = join(root, 'Cargo.toml');
  if (!existsSync(manifest)) return paths;
  let inSection = false;
  for (const raw of readFileSync(manifest, 'utf8').split(/\r?\n/)) {
    const line = raw.replace(/#.*$/, '').trim();
    const section = line.match(/^\[(.+)\]$/);
    if (section) {
      inSection = section[1] === 'workspace.dependencies';
      continue;
    }
    const entry = inSection && line.match(/^([A-Za-z0-9_-]+)\s*=\s*\{.*path\s*=\s*"([^"]+)"/);
    if (entry) paths.set(entry[1], resolve(root, entry[2]));
  }
  return paths;
}

function packageName(crateDir) {
  const manifest = join(crateDir, 'Cargo.toml');
  const name = existsSync(manifest) && readFileSync(manifest, 'utf8').match(/^\s*name\s*=\s*"([^"]+)"/m);
  return name ? name[1] : '';
}

function rustFiles(dir) {
  const files = [];
  const walk = (current) => {
    for (const entry of readdirSync(current)) {
      const path = join(current, entry);
      if (statSync(path).isDirectory()) {
        if (entry !== 'target') walk(path);
      } else if (entry.endsWith('.rs')) {
        files.push(path);
      }
    }
  };
  if (existsSync(dir)) walk(dir);
  return files;
}

// The top-level modules `text` names through `prefix::m` or `prefix::{.., m, ..}`.
function namedModules(text, prefix) {
  const names = new Set();
  for (const match of text.matchAll(new RegExp(`\\b${prefix}::(\\w+)`, 'g'))) names.add(match[1]);
  for (const match of text.matchAll(new RegExp(`\\b${prefix}::\\{([^}]*)\\}`, 'g'))) {
    for (const part of match[1].split(',')) {
      const name = part.trim().match(/^(\w+)/);
      if (name) names.add(name[1]);
    }
  }
  return names;
}

// Non-blank lines of the Rust code linked into the shipped binaries, split by whether it is
// generated. See the header for the rule.
export function rustLineShare(root) {
  const share = {
    generated: 0,
    handWritten: 0,
    total: 0,
    generatedFiles: 0,
    files: 0,
    crates: [],
    generatedModules: [],
  };
  const workspacePaths = workspaceDependencyPaths(root);
  const shipped = new Set();
  const queue = SHIPPED_CRATES.map((dir) => resolve(root, dir)).filter((dir) => existsSync(dir));
  while (queue.length) {
    const dir = queue.shift();
    if (shipped.has(dir)) continue;
    shipped.add(dir);
    queue.push(...linkedCrates(dir, workspacePaths));
  }

  const handTexts = [];
  const generatedCrates = [];
  for (const dir of shipped) {
    const src = join(dir, 'src');
    const lib = join(src, 'lib.rs');
    const wholeCrateGenerated = existsSync(lib) && isGenerated(readFileSync(lib, 'utf8'));
    share.crates.push(packageName(dir));
    if (wholeCrateGenerated) {
      generatedCrates.push({ dir, src, ident: packageName(dir).replace(/-/g, '_') });
      continue;
    }
    for (const path of rustFiles(src)) {
      const text = readFileSync(path, 'utf8');
      share.files += 1;
      if (isGenerated(text)) {
        share.generated += nonBlank(text);
        share.generatedFiles += 1;
      } else {
        share.handWritten += nonBlank(text);
        handTexts.push(text);
      }
    }
  }

  for (const { src, ident } of generatedCrates) {
    const moduleText = (name) => {
      const path = join(src, `${name}.rs`);
      return existsSync(path) ? readFileSync(path, 'utf8') : null;
    };
    const referenced = new Set();
    const pending = [];
    for (const text of handTexts) for (const name of namedModules(text, ident)) pending.push(name);
    while (pending.length) {
      const name = pending.pop();
      if (referenced.has(name) || name === 'lib') continue;
      const text = moduleText(name);
      if (text === null) continue;
      referenced.add(name);
      for (const next of namedModules(text, 'crate')) pending.push(next);
    }
    if (referenced.size === 0) continue;
    for (const name of ['lib', ...[...referenced].sort()]) {
      const text = moduleText(name);
      if (text === null) continue;
      share.files += 1;
      share.generatedFiles += 1;
      share.generated += nonBlank(text);
      if (name !== 'lib') share.generatedModules.push(`${ident}::${name}`);
    }
  }

  share.crates.sort();
  share.total = share.generated + share.handWritten;
  return share;
}

// Generated tests passing, from cargo test output (stdout followed by stderr, as the gate records it).
//
// Each test binary prints "Running <root source file>" (or "Doc-tests <crate>") on stderr, in the same
// order as its "running N tests" block on stdout. The k-th block is paired with the k-th Running line.
// A test is mapped to the file its module path names: for a binary whose root is in a src directory,
// the deepest existing module file (src/a/b.rs or src/a/b/mod.rs for the path a::b::name), else the
// root file itself (lib.rs, main.rs, or tests/x.rs for an integration test). A test is generated when
// that file is generated. Tests of doc-tests and unpaired binaries are reported as unmapped.
export function generatedTests(root, cargoText) {
  const result = { total: 0, passed: 0, unmapped: 0 };
  const lines = cargoText.split(/\r?\n/);

  const runs = [];
  const blocks = [];
  let current = null;
  for (const line of lines) {
    const run = line.match(/^\s*(Running|Doc-tests)\s+(?:unittests\s+)?(.+?)\s*(?:\([^()]*\))?\s*$/);
    if (run) {
      runs.push(run[1] === 'Running' ? run[2].replace(/\\/g, '/') : null);
      continue;
    }
    if (/^running \d+ tests?\s*$/.test(line)) {
      current = [];
      blocks.push(current);
      continue;
    }
    const test = line.match(/^test (\S+) \.\.\. (ok|FAILED)\s*$/);
    if (test && current) current.push({ name: test[1], passed: test[2] === 'ok' });
  }

  const all = blocks.reduce((sum, block) => sum + block.length, 0);
  if (runs.length !== blocks.length) {
    result.unmapped = all;
    return result;
  }

  const generatedOf = new Map();
  const isGeneratedFile = (file) => {
    if (!generatedOf.has(file)) generatedOf.set(file, isGenerated(readFileSync(join(root, file), 'utf8')));
    return generatedOf.get(file);
  };

  blocks.forEach((block, index) => {
    const rootFile = runs[index];
    if (!rootFile || !existsSync(join(root, rootFile))) {
      result.unmapped += block.length;
      return;
    }
    for (const test of block) {
      const file = testFile(root, rootFile, test.name);
      if (!isGeneratedFile(file)) continue;
      result.total += 1;
      if (test.passed) result.passed += 1;
    }
  });
  return result;
}

function testFile(root, rootFile, name) {
  const base = dirname(rootFile);
  if (!/(^|\/)src$/.test(base)) return rootFile;
  const modules = name.split('::').slice(0, -1);
  for (let k = modules.length; k >= 1; k -= 1) {
    const stem = [base, ...modules.slice(0, k)].join('/');
    if (existsSync(join(root, `${stem}.rs`))) return `${stem}.rs`;
    if (existsSync(join(root, `${stem}/mod.rs`))) return `${stem}/mod.rs`;
  }
  return rootFile;
}
